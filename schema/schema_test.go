const devicePath = "../examples/device_management/schema/device.yaml"

func TestParseDeviceExample(t *testing.T) {
	m, err := LoadFiles(devicePath)
	if err != nil {
		t.Fatal(err)
	}
	if got := len(m.ClassNames()); got != 6 {
		t.Fatalf("classes = %d, want 6", got)
	}
	nd := m.Class("NetworkDevice")
	if nd.ParentClass == nil || nd.ParentClass.Name != "Device" {
		t.Fatalf("NetworkDevice parent not resolved")
	}
	if !nd.HasSlot("hostname") || !nd.HasSlot("ip_address") {
		t.Errorf("NetworkDevice should have inherited hostname and own ip_address")
	}
	if nd.OwnSlot("hostname") != nil {
		t.Errorf("hostname should not be an own slot of NetworkDevice")
	}
	if s := m.Class("Device").Slot("status"); s.EnumObj == nil || s.EnumObj.Name != "DeviceStatus" {
		t.Errorf("enum object not attached")
	}
	if m.Class("DeviceClass").EffectiveTable() != "device_classes" {
		t.Errorf("table = %s", m.Class("DeviceClass").EffectiveTable())
	}
	// belongs_to Device -> DeviceClass gets an inverse has_many.
	if r := m.Class("DeviceClass").Relationship("devices"); r == nil || !r.IsHasMany() || r.Via != "device_class_id" {
		t.Errorf("auto has_many devices missing: %+v", r)
	}
	// Explicit has_many is not duplicated.
	n := 0
	for _, r := range nd.Relationships {
		if r.IsHasMany() && r.Target == "Interface" {
			n++
		}
	}
	if n != 1 {
		t.Errorf("NetworkDevice has %d has_many Interface, want 1", n)
	}
	if !strings.HasSuffix(m.Hash(), "") || len(m.Hash()) != 32 {
		t.Errorf("hash %q", m.Hash())
	}
}

func TestMergeLaterDocumentWins(t *testing.T) {
	m, err := Parse(String(`
schema_version: "1.0.0"
classes:
  A: {slots: [{name: x, type: string}]}
`), String(`
schema_version: "1.1.0"
classes:
  A: {slots: [{name: y, type: integer}]}
  B: {slots: [{name: z, type: text}]}
`))
	if err != nil {
		t.Fatal(err)
	}
	if m.SchemaVersion != "1.1.0" || m.Class("A").OwnSlot("y") == nil || m.Class("A").OwnSlot("x") != nil || m.Class("B") == nil {
		t.Fatalf("merge wrong: %s %+v", m.SchemaVersion, m.Class("A").Slots)
	}
}

func TestParseErrors(t *testing.T) {
	cases := map[string]string{
		"missing type":  `classes: {A: {slots: [{name: x}]}}`,
		"bad type":      `classes: {A: {slots: [{name: x, type: blob}]}}`,
		"enum no name":  `classes: {A: {slots: [{name: x, type: enum}]}}`,
		"bt no via":     `classes: {A: {relationships: {belongs_to: [{target: B}]}}}`,
		"enum no vals":  `enums: {E: {default: a}}`,
		"enum bad def":  `enums: {E: {values: [a, b], default: c}}`,
		"dup slot":      `classes: {A: {slots: [{name: x, type: string}, {name: x, type: string}]}}`,
		"bad on_delete": `classes: {A: {slots: [{name: b_id, type: integer}], relationships: {belongs_to: [{target: B, via: b_id, on_delete: explode}]}}}`,
	}
	for name, doc := range cases {
		if _, err := Parse(String(doc)); err == nil {
			t.Errorf("%s: expected parse error", name)
		}
	}
}

func TestValidatorProblems(t *testing.T) {
	m, err := Parse(String(`
enums:
  E: {values: [a, b]}
classes:
  A:
    is_a: Missing
    display: nope
    slots:
      - {name: id, type: integer, autogenerated: true, default: 1}
      - {name: e, type: enum, enum: E, default: z}
      - {name: f, type: enum, enum: Nope}
      - {name: d, type: date, min: 1}
      - {name: n, type: integer, pattern: '^\d+$'}
      - {name: s, type: string, pattern: '([unclosed'}
      - {name: b_id, type: integer}
    relationships:
      belongs_to: [{target: B, via: b_id}, {target: A, via: missing_fk}]
      many_to_many: [{target: A, through: NoJoin}]
    constraints:
      unique: [ghost]
    access: {owner: who, read: everyone}
  C: {is_a: D}
  D: {is_a: C}
  U:
    slots: [{name: email, type: string}, {name: pw, type: string}]
    auth: {login: email, password: pw}
`))
	if err != nil {
		t.Fatal(err)
	}
	Resolve(m)
	problems := strings.Join(Validate(m), "\n")
	for _, want := range []string{
		"parent class 'Missing' is not defined",
		"autogenerated field should not have a default",
		"default 'z' is not a valid value for enum 'E'",
		"enum 'Nope' is not defined",
		"min/max are only valid",
		"pattern is only valid for string or text",
		"is not a valid regex",
		"target class 'B' is not defined",
		"FK field 'missing_fk' does not exist",
		"through class 'NoJoin' is not defined",
		"column 'ghost' is not defined",
		"display slot 'nope' is not defined",
		"owner slot 'who' is not defined",
		"read must be public, authenticated or owner",
		"Inheritance cycle detected",
		"must exist and have type password",
	} {
		if !strings.Contains(problems, want) {
			t.Errorf("missing problem %q in:\n%s", want, problems)
		}
	}
}

func TestDefaultsAndBooleans(t *testing.T) {
	m, err := Load(String(`
classes:
  A:
    slots:
      - {name: on, type: boolean, default: true}
      - {name: n, type: integer, default: 5, min: 1, max: 10}
      - {name: s, type: string, max: 40, ui_order: 3}
`))
	if err != nil {
		t.Fatal(err)
	}
	a := m.Class("A")
	if *a.Slot("on").Default != "1" || *a.Slot("n").Default != "5" {
		t.Errorf("defaults: %q %q", *a.Slot("on").Default, *a.Slot("n").Default)
	}
	if *a.Slot("n").Max != 10 || a.Slot("s").UIOrder != 3 || a.Slot("on").UIOrder != 999 {
		t.Errorf("numeric attrs wrong")
	}
	if a.EffectiveTable() != "as" {
		t.Errorf("table %s", a.EffectiveTable())
	}
}
