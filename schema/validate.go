package schema

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/timeofmind/data-driven-framework-go/model"
)

// ValidationError collects every semantic problem found in a model.
type ValidationError struct{ Problems []string }

func (e *ValidationError) Error() string {
	return "schema validation failed:\n  - " + strings.Join(e.Problems, "\n  - ")
}

// Validate checks the model's semantics and returns every problem found.
func Validate(m *model.Model) []string {
	var errs []string
	for _, e := range m.Enums() {
		for _, v := range e.Values {
			if v == "" {
				errs = append(errs, fmt.Sprintf("Enum '%s': value must be a non-empty string", e.Name))
			}
		}
	}
	for _, c := range m.Classes() {
		errs = append(errs, validateClass(c, m)...)
	}
	errs = append(errs, inheritanceCycles(m)...)
	return errs
}

// ValidateOrError returns a *ValidationError when the model has problems.
func ValidateOrError(m *model.Model) error {
	if p := Validate(m); len(p) > 0 {
		return &ValidationError{Problems: p}
	}
	return nil
}

var numericOrString = map[string]bool{"integer": true, "float": true, "duration": true, "string": true, "text": true, "password": true}

func validateClass(c *model.Class, m *model.Model) []string {
	var errs []string
	add := func(format string, a ...any) { errs = append(errs, fmt.Sprintf(format, a...)) }
	cn := c.Name

	if c.HasParent() && !m.HasClass(c.IsA) {
		add("Class '%s': parent class '%s' is not defined", cn, c.IsA)
	}

	seen := map[string]bool{}
	for _, s := range c.Slots {
		if seen[s.Name] {
			add("Class '%s': duplicate slot '%s'", cn, s.Name)
		}
		seen[s.Name] = true
		if s.Type == "enum" {
			e := m.Enum(s.Enum)
			if e == nil {
				add("Class '%s', slot '%s': enum '%s' is not defined", cn, s.Name, s.Enum)
			} else if s.Default != nil && !e.HasValue(*s.Default) {
				add("Class '%s', slot '%s': default '%s' is not a valid value for enum '%s'", cn, s.Name, *s.Default, s.Enum)
			}
		}
		if s.Autogenerated && s.Default != nil {
			add("Class '%s', slot '%s': autogenerated field should not have a default value (it is set by the database)", cn, s.Name)
		}
		if (s.Min != nil || s.Max != nil) && !numericOrString[s.Type] {
			add("Class '%s', slot '%s': min/max are only valid for integer, float, or string types", cn, s.Name)
		}
		if s.Pattern != "" {
			if s.Type != "string" && s.Type != "text" {
				add("Class '%s', slot '%s': pattern is only valid for string or text types", cn, s.Name)
			}
			if _, err := regexp.Compile(s.Pattern); err != nil {
				add("Class '%s', slot '%s': pattern '%s' is not a valid regex: %v", cn, s.Name, s.Pattern, err)
			}
		}
	}

	for _, r := range c.Relationships {
		if !m.HasClass(r.Target) {
			add("Class '%s', relationship '%s': target class '%s' is not defined", cn, r.Name, r.Target)
			continue
		}
		if r.IsBelongsTo() && !c.HasSlot(r.Via) {
			add("Class '%s', relationship '%s' (belongs_to): FK field '%s' does not exist on this class", cn, r.Name, r.Via)
		}
		if r.IsManyToMany() && !m.HasClass(r.Through) {
			add("Class '%s', relationship '%s' (many_to_many): through class '%s' is not defined", cn, r.Name, r.Through)
		}
		if r.OrderBy != "" {
			if t := m.Class(r.Target); t != nil && !t.HasSlot(orderSlot(r.OrderBy)) {
				add("Class '%s', relationship '%s': order_by slot '%s' is not defined on '%s'", cn, r.Name, orderSlot(r.OrderBy), r.Target)
			}
		}
	}

	for _, k := range c.Constraints {
		for _, col := range k.Columns {
			if !c.HasSlot(col) {
				add("Class '%s', constraint: column '%s' is not defined as a slot", cn, col)
			}
		}
	}

	for attr, slot := range map[string]string{"display": c.Display, "order_by": orderSlot(c.OrderBy), "calendar": c.Calendar} {
		if slot != "" && !c.HasSlot(slot) {
			add("Class '%s': %s slot '%s' is not defined", cn, attr, slot)
		}
	}
	if c.Calendar != "" {
		if s := c.Slot(c.Calendar); s != nil && s.Type != "date" && s.Type != "datetime" {
			add("Class '%s': calendar slot '%s' must be a date or datetime", cn, c.Calendar)
		}
	}

	if a := c.Access; a != nil {
		if a.Owner != "" && !c.HasSlot(a.Owner) {
			add("Class '%s', access: owner slot '%s' is not defined", cn, a.Owner)
		}
		if a.Read != "" && !oneOf(a.Read, "public", "authenticated", "owner") {
			add("Class '%s', access: read must be public, authenticated or owner (got '%s')", cn, a.Read)
		}
		if a.Write != "" && !oneOf(a.Write, "owner", "authenticated", "nobody") {
			add("Class '%s', access: write must be owner, authenticated or nobody (got '%s')", cn, a.Write)
		}
		if (a.Read == "owner" || a.Write == "owner") && a.Owner == "" {
			add("Class '%s', access: read/write 'owner' requires an owner slot", cn)
		}
		for slot := range a.PublicWhen {
			if !c.HasSlot(slot) {
				add("Class '%s', access: public_when slot '%s' is not defined", cn, slot)
			}
		}
	}
	if a := c.Auth; a != nil {
		if a.Login == "" || !c.HasSlot(a.Login) {
			add("Class '%s', auth: login slot '%s' is not defined", cn, a.Login)
		}
		if s := c.Slot(a.Password); s == nil || s.Type != "password" {
			add("Class '%s', auth: password slot '%s' must exist and have type password", cn, a.Password)
		}
		if a.Display != "" && !c.HasSlot(a.Display) {
			add("Class '%s', auth: display slot '%s' is not defined", cn, a.Display)
		}
	}
	return errs
}

func inheritanceCycles(m *model.Model) []string {
	var errs []string
	for _, c := range m.Classes() {
		seen := map[string]bool{}
		for cur := c; cur != nil && cur.HasParent(); cur = m.Class(cur.IsA) {
			if seen[cur.Name] {
				errs = append(errs, fmt.Sprintf("Inheritance cycle detected involving class '%s'", c.Name))
				break
			}
			seen[cur.Name] = true
		}
	}
	return errs
}

// orderSlot extracts the slot name from "slot [asc|desc]".
func orderSlot(spec string) string {
	f := strings.Fields(spec)
	if len(f) == 0 {
		return ""
	}
	return f[0]
}

func oneOf(v string, opts ...string) bool {
	for _, o := range opts {
		if v == o {
			return true
		}
	}
	return false
}
