// Package reverse builds a YAML schema from an existing database (best effort:
// complex types may need manual review). MySQL/MariaDB and SQLite.
package reverse

import (
	"context"
	"database/sql"
	"fmt"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/timeofmind/data-driven-framework-go/model"
)

type column struct {
	Name, Type, Comment string
	Nullable, AutoInc   bool
	Default             *string
	MaxLen              *int64
}

type foreignKey struct{ Column, RefTable, RefColumn string }

type index struct {
	Name    string
	Unique  bool
	Columns []string
}

// Introspect reads the database and returns a schema document.
// dialectName is "mysql" or "sqlite".
func Introspect(ctx context.Context, db *sql.DB, dialectName string) (map[string]any, error) {
	in := introspector{db: db, ctx: ctx, sqlite: strings.HasPrefix(dialectName, "sqlite")}
	dbName := "main"
	if !in.sqlite {
		if err := db.QueryRowContext(ctx, "SELECT DATABASE()").Scan(&dbName); err != nil {
			return nil, fmt.Errorf("cannot determine current database: %w", err)
		}
	}
	tables, err := in.tables()
	if err != nil {
		return nil, err
	}
	classes := map[string]any{}
	enums := map[string]any{}
	for _, t := range tables {
		if strings.HasPrefix(t, "_framework_") || strings.HasPrefix(t, "sqlite_") {
			continue
		}
		cols, err := in.columns(t)
		if err != nil {
			return nil, err
		}
		fks, err := in.foreignKeys(t)
		if err != nil {
			return nil, err
		}
		idxs, err := in.indexes(t)
		if err != nil {
			return nil, err
		}
		className := TableToClass(t)
		var slots []any
		for i, c := range cols {
			slots = append(slots, toSlot(className, c, i+1, enums))
		}
		def := map[string]any{
			"label":       model.SplitCamel(className),
			"description": "reverse-generated from table " + t,
			"table":       t,
			"slots":       slots,
		}
		var bt []any
		for _, fk := range fks {
			bt = append(bt, map[string]any{"target": TableToClass(fk.RefTable), "via": fk.Column})
		}
		if len(bt) > 0 {
			def["relationships"] = map[string]any{"belongs_to": bt}
		}
		var uniques []any
		var others []any
		for _, ix := range idxs {
			if ix.Name == "PRIMARY" {
				continue
			}
			if ix.Unique {
				uniques = append(uniques, ix.Columns)
			} else {
				others = append(others, map[string]any{"columns": ix.Columns})
			}
		}
		cons := map[string]any{}
		if len(uniques) == 1 {
			cons["unique"] = uniques[0]
		} else if len(uniques) > 1 {
			cons["unique"] = uniques
		}
		if len(others) > 0 {
			cons["indexes"] = others
		}
		if len(cons) > 0 {
			def["constraints"] = cons
		}
		classes[className] = def
	}
	doc := map[string]any{
		"schema_version":    "1.0.0",
		"framework_version": "0.01",
		"description":       "reverse-generated from database " + dbName,
		"classes":           classes,
	}
	if len(enums) > 0 {
		doc["enums"] = enums
	}
	return doc, nil
}

// YAML is Introspect rendered as YAML.
func YAML(ctx context.Context, db *sql.DB, dialectName string) ([]byte, error) {
	doc, err := Introspect(ctx, db, dialectName)
	if err != nil {
		return nil, err
	}
	return yaml.Marshal(doc)
}

func toSlot(className string, c column, pos int, enums map[string]any) map[string]any {
	typ := model.FromMySQLType(c.Type)
	s := map[string]any{"name": c.Name, "type": typ, "ui_order": pos}
	if typ == "enum" {
		name := className + toPascal(c.Name)
		enums[name] = map[string]any{"values": enumValues(c.Type)}
		s["enum"] = name
	}
	lower := strings.ToLower(c.Type)
	if c.AutoInc || ((c.Name == "created_at" || c.Name == "updated_at") && c.Default != nil &&
		strings.Contains(strings.ToUpper(*c.Default), "CURRENT_TIMESTAMP")) {
		s["autogenerated"] = true
		s["read_only"] = true
	} else if c.Default != nil && strings.ToUpper(*c.Default) != "NULL" {
		s["default"] = strings.Trim(*c.Default, "'")
	}
	if !c.Nullable || c.AutoInc {
		s["required"] = true
	}
	if typ == "string" && c.MaxLen != nil && *c.MaxLen != 255 {
		s["max"] = *c.MaxLen
	}
	if typ == "text" && strings.Contains(lower, "blob") {
		s["description"] = "binary column " + c.Type + " (review)"
	}
	if c.Comment != "" {
		s["description"] = c.Comment
	}
	s["label"] = (&model.Slot{Name: c.Name}).EffectiveLabel()
	return s
}

func enumValues(colType string) []string {
	i, j := strings.IndexByte(colType, '('), strings.LastIndexByte(colType, ')')
	if i < 0 || j <= i {
		return nil
	}
	var out []string
	for _, v := range strings.Split(colType[i+1:j], ",") {
		out = append(out, strings.Trim(strings.TrimSpace(v), "'"))
	}
	return out
}

// TableToClass converts a table name to a class name: device_classes -> DeviceClass.
func TableToClass(table string) string {
	singular := table
	switch {
	case strings.HasSuffix(table, "ies"):
		singular = strings.TrimSuffix(table, "ies") + "y"
	case strings.HasSuffix(table, "sses"):
		singular = strings.TrimSuffix(table, "es")
	case strings.HasSuffix(table, "s") && !strings.HasSuffix(table, "ss"):
		singular = strings.TrimSuffix(table, "s")
	}
	return toPascal(singular)
}

func toPascal(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

type introspector struct {
	db     *sql.DB
	ctx    context.Context
	sqlite bool
}

func (in introspector) tables() ([]string, error) {
	q := "SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME"
	if in.sqlite {
		q = "SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name"
	}
	rows, err := in.db.QueryContext(in.ctx, q)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var n string
		if err := rows.Scan(&n); err != nil {
			return nil, err
		}
		out = append(out, n)
	}
	return out, rows.Err()
}

func (in introspector) columns(table string) ([]column, error) {
	var out []column
	if in.sqlite {
		rows, err := in.db.QueryContext(in.ctx, "SELECT name, type, \"notnull\", dflt_value, pk FROM pragma_table_info(?)", table)
		if err != nil {
			return nil, err
		}
		defer rows.Close()
		for rows.Next() {
			var c column
			var notnull, pk int
			var def sql.NullString
			if err := rows.Scan(&c.Name, &c.Type, &notnull, &def, &pk); err != nil {
				return nil, err
			}
			c.Nullable = notnull == 0 && pk == 0
			c.AutoInc = pk == 1 && strings.EqualFold(c.Type, "INTEGER")
			if def.Valid {
				c.Default = &def.String
			}
			c.Type = sqliteToMySQLType(c.Type)
			out = append(out, c)
		}
		return out, rows.Err()
	}
	rows, err := in.db.QueryContext(in.ctx, `SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, EXTRA,
		COLUMN_COMMENT, CHARACTER_MAXIMUM_LENGTH FROM INFORMATION_SCHEMA.COLUMNS
		WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION`, table)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	for rows.Next() {
		var c column
		var nullable, extra string
		var def sql.NullString
		var maxLen sql.NullInt64
		if err := rows.Scan(&c.Name, &c.Type, &nullable, &def, &extra, &c.Comment, &maxLen); err != nil {
			return nil, err
		}
		c.Nullable = nullable == "YES"
		c.AutoInc = strings.Contains(strings.ToLower(extra), "auto_increment")
		if def.Valid {
			c.Default = &def.String
		}
		if maxLen.Valid {
			c.MaxLen = &maxLen.Int64
		}
		out = append(out, c)
	}
	return out, rows.Err()
}

func sqliteToMySQLType(t string) string {
	switch strings.ToUpper(t) {
	case "INTEGER", "INT":
		return "INT"
	case "REAL", "FLOAT", "DOUBLE":
		return "DOUBLE"
	case "TEXT", "":
		return "VARCHAR(255)"
	}
	return t
}

func (in introspector) foreignKeys(table string) ([]foreignKey, error) {
	q := `SELECT kcu.COLUMN_NAME, kcu.REFERENCED_TABLE_NAME, kcu.REFERENCED_COLUMN_NAME
		FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu
		JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
		  ON tc.CONSTRAINT_NAME = kcu.CONSTRAINT_NAME AND tc.TABLE_SCHEMA = kcu.TABLE_SCHEMA AND tc.TABLE_NAME = kcu.TABLE_NAME
		WHERE kcu.TABLE_SCHEMA = DATABASE() AND kcu.TABLE_NAME = ? AND tc.CONSTRAINT_TYPE = 'FOREIGN KEY'
		ORDER BY kcu.COLUMN_NAME`
	if in.sqlite {
		q = `SELECT "from", "table", "to" FROM pragma_foreign_key_list(?) ORDER BY "from"`
	}
	rows, err := in.db.QueryContext(in.ctx, q, table)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []foreignKey
	for rows.Next() {
		var fk foreignKey
		var to sql.NullString
		if err := rows.Scan(&fk.Column, &fk.RefTable, &to); err != nil {
			return nil, err
		}
		fk.RefColumn = to.String
		out = append(out, fk)
	}
	return out, rows.Err()
}

func (in introspector) indexes(table string) ([]index, error) {
	byName := map[string]*index{}
	if in.sqlite {
		rows, err := in.db.QueryContext(in.ctx, `SELECT name, "unique" FROM pragma_index_list(?) WHERE origin != 'pk'`, table)
		if err != nil {
			return nil, err
		}
		var names []string
		for rows.Next() {
			var n string
			var u int
			if err := rows.Scan(&n, &u); err != nil {
				rows.Close()
				return nil, err
			}
			byName[n] = &index{Name: n, Unique: u == 1}
			names = append(names, n)
		}
		rows.Close()
		for _, n := range names {
			crow, err := in.db.QueryContext(in.ctx, "SELECT name FROM pragma_index_info(?) ORDER BY seqno", n)
			if err != nil {
				return nil, err
			}
			for crow.Next() {
				var c string
				crow.Scan(&c)
				byName[n].Columns = append(byName[n].Columns, c)
			}
			crow.Close()
		}
	} else {
		rows, err := in.db.QueryContext(in.ctx, `SELECT INDEX_NAME, NON_UNIQUE, COLUMN_NAME FROM INFORMATION_SCHEMA.STATISTICS
			WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ? ORDER BY INDEX_NAME, SEQ_IN_INDEX`, table)
		if err != nil {
			return nil, err
		}
		defer rows.Close()
		for rows.Next() {
			var n, col string
			var nonUnique int
			if err := rows.Scan(&n, &nonUnique, &col); err != nil {
				return nil, err
			}
			if byName[n] == nil {
				byName[n] = &index{Name: n, Unique: nonUnique == 0}
			}
			byName[n].Columns = append(byName[n].Columns, col)
		}
	}
	names := make([]string, 0, len(byName))
	for n := range byName {
		names = append(names, n)
	}
	sort.Strings(names)
	out := make([]index, 0, len(names))
	for _, n := range names {
		out = append(out, *byName[n])
	}
	return out, nil
}
