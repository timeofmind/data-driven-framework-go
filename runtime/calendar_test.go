package runtime_test

import (
	"strings"
	"testing"

	"github.com/timeofmind/data-driven-framework-go/runtime"
	"github.com/timeofmind/data-driven-framework-go/schema"
)

// A meet runs over several days (calendar_end); an entry takes its dates and
// its calendar text from the meet it links to (calendar paths).
const calendarSchema = `
classes:
  Meet:
    display: name
    calendar: start_date
    calendar_end: end_date
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: name, type: string, required: true}
      - {name: start_date, type: date, required: true}
      - {name: end_date, type: date}
  Entry:
    calendar: meet.start_date
    calendar_end: meet.end_date
    calendar_label: "meet.name + ' · ' + events"
    title: "meet.name"
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: meet_id, type: integer, required: true}
      - {name: events, type: string}
    relationships:
      belongs_to: [{target: Meet, via: meet_id}]
`

func TestCalendarSpans(t *testing.T) {
	m := mustLoad(t, calendarSchema)
	for name, reg := range backends(t, m) {
		t.Run(name, func(t *testing.T) {
			meets, entries := reg.MustClass("Meet"), reg.MustClass("Entry")
			indoor := meets.New(map[string]any{"name": "Indoor champs", "start_date": "2027-03-12", "end_date": "2027-03-14"})
			jerome := meets.New(map[string]any{"name": "Harry Jerome", "start_date": "2027-02-06"})
			later := meets.New(map[string]any{"name": "Spring 5K", "start_date": "2027-04-10"})
			for _, r := range []*runtime.Record{indoor, jerome, later} {
				if err := meets.Save(ctx, r); err != nil {
					t.Fatal(err)
				}
			}
			spans, err := meets.CalendarSpans(ctx, runtime.Query{}, "2027-03-13", "2027-03-31")
			if err != nil || len(spans) != 1 || spans[0].From != "2027-03-12" || spans[0].To != "2027-03-14" {
				t.Fatalf("a meet still running on the 13th: %v %+v", err, spans)
			}
			e1 := entries.New(map[string]any{"meet_id": indoor.ID(), "events": "60 m, 300 m"})
			e2 := entries.New(map[string]any{"meet_id": jerome.ID(), "events": "300 m"})
			entries.Save(ctx, e1)
			entries.Save(ctx, e2)
			spans, err = entries.CalendarSpans(ctx, runtime.Query{}, "2027-02-01", "2027-03-12")
			if err != nil || len(spans) != 2 || spans[0].Rec.ID() != e2.ID() || spans[1].From != "2027-03-12" || spans[1].To != "2027-03-14" {
				t.Fatalf("entries take the meets' dates: %v %+v", err, spans)
			}
			if got := runtime.CalendarText(spans[1].Rec); got != "Indoor champs · 60 m, 300 m" {
				t.Errorf("calendar text through the link: %q", got)
			}
			if got := spans[1].Rec.Title(); got != "Indoor champs" {
				t.Errorf("title through the link: %q", got)
			}
			if spans, _ := entries.CalendarSpans(ctx, runtime.Query{}, "2027-03-15", "2027-03-31"); len(spans) != 0 {
				t.Errorf("nothing after the meet: %+v", spans)
			}
		})
	}
	for bad, want := range map[string]string{
		"calendar: meet.start_date\n":  `calendar "meet.nope"`,
		"calendar_end: meet.end_date\n": `calendar_end 'meet.name' must be a date`,
	} {
		repl := map[string]string{"calendar: meet.start_date\n": "calendar: meet.nope\n", "calendar_end: meet.end_date\n": "calendar_end: meet.name\n"}[bad]
		_, err := schema.Load(schema.String(strings.Replace(calendarSchema, "    "+bad, "    "+repl, 1)))
		if err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("want %q, got %v", want, err)
		}
	}
}
