package runtime_test

import (
	"strings"
	"testing"

	"github.com/timeofmind/data-driven-framework-go/runtime"
)

// A neutral fixture: a reading club. Members log reading sessions against
// their own books (imported from an e-reader export), books are marked
// finished by a trigger, and challenges collect entries with a leaderboard.
const clubSchema = `
enums:
  BookState: {values: [reading, finished, abandoned], default: reading}
  Format: {values: [paper, ebook, audio, other], default: paper}
classes:
  Member:
    display: name
    auth: {login: email, password: pw}
    access: {owner: id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: email, type: string, required: true, hidden: true}
      - {name: pw, type: password, required: true}
      - {name: name, type: string, required: true}
      - {name: tz, type: string, default: "Europe/London"}
  Book:
    display: title
    access: {owner: member_id, read: owner}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: member_id, type: integer, required: true}
      - {name: title, type: string, required: true}
      - {name: pages, type: integer}
      - {name: pages_read, type: integer, default: 0}
      - {name: state, type: enum, enum: BookState, default: reading}
    relationships:
      belongs_to: [{target: Member, via: member_id, on_delete: cascade}]
  Session:
    display: note
    calendar: day
    calendar_label: "note + ' (' + pages + ' p)'"
    access: {owner: member_id, read: owner}
    computed:
      - {name: speed, label: "Pages per hour", expr: "pages / (minutes / 60)", format: number, decimals: 1, when: "minutes > 0"}
      - {name: per_page, label: "Time per page", expr: "minutes / pages", format: duration}
    triggers:
      - via: book_id
        if: "target.state == 'reading'"
        set:
          pages_read: "target.pages_read + self.pages"
          state: "if(target.pages_read + self.pages >= target.pages, 'finished', 'reading')"
    import:
      formats: [csv]
      dedupe: ref
      timezone: "owner.tz"
      fields: {day: date_local, note: title, pages: pages, minutes: minutes, format: format, ref: file_hash}
      fallback: {format: other}
      children:
        - {relationship: highlights, from: notes, min: 1, fields: {n: index, text: text}}
      link:
        - via: book_id
          where: {member_id: self.member_id}
          if: "lower(item.title) == lower(self.note)"
          prefer: "item.state == 'reading'"
      create:
        - class: Entry
          from: {class: Signup, where: {member_id: self.member_id}, follow: challenge_id}
          if: "item.min_pages <= self.pages"
          unique: [challenge_id, session_id]
          set: {challenge_id: item.id, session_id: self.id, minutes: self.minutes}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: member_id, type: integer, required: true}
      - {name: book_id, type: integer}
      - {name: day, type: date, required: true}
      - {name: note, type: string, required: true, max: 12}
      - {name: pages, type: integer, required: true}
      - {name: minutes, type: duration}
      - {name: format, type: enum, enum: Format, default: paper}
      - {name: ref, type: string}
    relationships:
      belongs_to:
        - {target: Member, via: member_id, on_delete: cascade}
        - {target: Book, via: book_id, on_delete: set_null}
      has_many:
        - {target: Highlight, via: session_id, name: highlights}
  Highlight:
    access: {parent: session_id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: session_id, type: integer, required: true}
      - {name: n, type: integer}
      - {name: text, type: text}
    relationships:
      belongs_to: [{target: Session, via: session_id, on_delete: cascade}]
  Challenge:
    display: title
    access: {owner: member_id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: member_id, type: integer, required: true}
      - {name: title, type: string, required: true}
      - {name: min_pages, type: integer, default: 1}
      - {name: open, type: boolean, default: true}
    relationships:
      belongs_to: [{target: Member, via: member_id, on_delete: cascade}]
      has_many:
        - {target: Entry, via: challenge_id, name: entries, order_by: "minutes asc", rank: {best_per: member_id}}
        - {target: Signup, via: challenge_id, name: signups, add_label: "Join", add_when: "open"}
  Signup:
    access: {owner: member_id, parent: challenge_id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: member_id, type: integer, required: true}
      - {name: challenge_id, type: integer, required: true}
    relationships:
      belongs_to:
        - {target: Member, via: member_id, on_delete: cascade}
        - {target: Challenge, via: challenge_id, on_delete: cascade}
  Entry:
    access: {owner: member_id, parent: challenge_id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: member_id, type: integer, required: true}
      - {name: challenge_id, type: integer, required: true}
      - {name: session_id, type: integer}
      - {name: minutes, type: duration, required: true}
    relationships:
      belongs_to:
        - {target: Member, via: member_id, on_delete: cascade}
        - {target: Challenge, via: challenge_id, on_delete: cascade}
        - {target: Session, via: session_id, on_delete: set_null}
`

func TestBehaviour(t *testing.T) {
	m := mustLoad(t, clubSchema)
	for name, reg := range backends(t, m) {
		t.Run(name, func(t *testing.T) {
			members, books, sessions := reg.MustClass("Member"), reg.MustClass("Book"), reg.MustClass("Session")
			ann := members.New(map[string]any{"email": "ann@x.org", "pw": "password!1", "name": "Ann", "tz": "America/Vancouver"})
			ben := members.New(map[string]any{"email": "ben@x.org", "pw": "password!1", "name": "Ben"})
			members.Save(ctx, ann)
			members.Save(ctx, ben)
			pa := runtime.PrincipalFor(ann)

			book := books.New(map[string]any{"member_id": ann.ID(), "title": "Dune", "pages": int64(400)})
			bensBook := books.New(map[string]any{"member_id": ben.ID(), "title": "Dune", "pages": int64(400)})
			books.Save(ctx, book)
			books.Save(ctx, bensBook)

			// Computed fields and calendar label.
			s := sessions.New(map[string]any{"member_id": ann.ID(), "day": "2026-11-01", "note": "Dune", "pages": int64(60), "minutes": int64(5400), "book_id": book.ID()})
			if err := sessions.Save(ctx, s); err != nil {
				t.Fatal(err)
			}
			cv := runtime.Computed(s)
			// minutes is a duration (seconds): 5400 s for 60 pages = 1:30 per page.
			if len(cv) != 2 || cv[0].Text != "0.7" || cv[1].Text != "1:30" {
				t.Errorf("computed: %+v", cv)
			}
			if got := runtime.CalendarText(s); got != "Dune (60 p)" {
				t.Errorf("calendar label %q", got)
			}

			// Trigger: the book's progress accumulates, and finishes at 400 pages.
			b, _ := books.Load(ctx, book.ID())
			if b.Int("pages_read") != 60 || b.String("state") != "reading" {
				t.Fatalf("after first session: %v", b.Values)
			}
			sessions.Save(ctx, sessions.New(map[string]any{"member_id": ann.ID(), "day": "2026-11-02", "note": "Dune", "pages": int64(340), "book_id": book.ID()}))
			b, _ = books.Load(ctx, book.ID())
			if b.Int("pages_read") != 400 || b.String("state") != "finished" {
				t.Fatalf("trigger did not finish the book: %v", b.Values)
			}

			// add_when.
			ch := reg.MustClass("Challenge")
			c1 := ch.New(map[string]any{"member_id": ben.ID(), "title": "50 pages", "min_pages": int64(50)})
			ch.Save(ctx, c1)
			if !runtime.AddAllowed(ch.Class.Relationship("signups"), c1) {
				t.Error("open challenge should allow joining")
			}
			c1.Set("open", false)
			if runtime.AddAllowed(ch.Class.Relationship("signups"), c1) {
				t.Error("closed challenge should not allow joining")
			}
			c1.Set("open", true)
			ch.Save(ctx, c1)
			c2 := ch.New(map[string]any{"member_id": ben.ID(), "title": "500 pages", "min_pages": int64(500)})
			ch.Save(ctx, c2)
			for _, c := range []*runtime.Record{c1, c2} {
				reg.MustClass("Signup").Save(ctx, reg.MustClass("Signup").New(map[string]any{"member_id": ann.ID(), "challenge_id": c.ID()}))
			}

			// Import: a new copy of the book to link to, then an e-reader item.
			book2 := books.New(map[string]any{"member_id": ann.ID(), "title": "Emma", "pages": int64(300)})
			books.Save(ctx, book2)
			src := runtime.ImportSource{
				Fields: map[string]any{"date_local": "2026-11-03", "title": "Emma", "pages": int64(80), "minutes": int64(3600),
					"format": "kindle", "file_hash": "abc123"},
				Children: map[string][]map[string]any{"notes": {{"text": "first"}, {"text": "second"}}},
			}
			out, err := sessions.Import(ctx, pa, src)
			if err != nil {
				t.Fatal(err)
			}
			rec := out.Record
			if rec.Int("member_id") != ann.ID() || rec.String("format") != "other" || rec.Int("book_id") != book2.ID() {
				t.Errorf("imported: %v", rec.Values)
			}
			if len(out.Created) != 1 || out.Created[0].ID() != c1.ID() {
				t.Errorf("created entries for %d challenges, want only the 50-page one", len(out.Created))
			}
			hl, _ := reg.MustClass("Highlight").List(ctx, runtime.Query{Where: []runtime.Cond{runtime.Eq("session_id", rec.ID())}, OrderBy: "n"})
			if len(hl) != 2 || hl[1].Int("n") != 2 || hl[1].String("text") != "second" {
				t.Errorf("children: %v", hl)
			}
			b2, _ := books.Load(ctx, book2.ID())
			if b2.Int("pages_read") != 80 {
				t.Error("trigger did not run for the imported session")
			}
			// Same file again: deduplicated.
			again, err := sessions.Import(ctx, pa, src)
			if err != nil || again.Duplicate == nil || again.Record != nil {
				t.Errorf("duplicate import: %v %+v", err, again)
			}
			// Over-long titles are truncated to the slot max; owners can't be overridden.
			src.Fields["file_hash"], src.Fields["title"] = "def", "A Very Long Book Title Indeed"
			out, err = sessions.Import(ctx, pa, src)
			if err != nil || out.Record.String("note") != "A Very Long" || out.Record.Int("book_id") != 0 {
				t.Errorf("truncation / no link: %v %v", err, out.Record.Values)
			}
			if !strings.HasPrefix(out.Record.String("note"), "A Very") {
				t.Errorf("note %q", out.Record.String("note"))
			}
			// Links never reach another member's rows, even with a matching title.
			src.Fields["file_hash"], src.Fields["title"] = "ghi", "Dune"
			pb := runtime.PrincipalFor(ben)
			out, err = sessions.Import(ctx, pb, src)
			if err != nil || out.Record.Int("book_id") != bensBook.ID() {
				t.Errorf("ben's import should link to ben's own Dune: %v %v", err, out.Record.Values)
			}
			if tz := reg.ImportTimezone(ctx, sessions.Class, pa, "UTC"); tz.String() != "America/Vancouver" {
				t.Errorf("timezone %s", tz)
			}
		})
	}
}

func TestBehaviourValidation(t *testing.T) {
	bad := strings.NewReplacer(
		`if: "lower(item.title) == lower(self.note)"`, `if: "item.nope == self.note"`,
		`expr: "pages / (minutes / 60)"`, `expr: "pages / (minutez / 60)"`,
		`set: {challenge_id: item.id, session_id: self.id, minutes: self.minutes}`, `set: {challenge_id: item.id, bogus: self.id, minutes: self.minutes}`,
		`rank: {best_per: member_id}`, `rank: {best_per: whoever}`,
	).Replace(clubSchema)
	_, err := loadErr(bad)
	if err == nil {
		t.Fatal("expected validation errors")
	}
	for _, want := range []string{`Book has no slot "nope"`, `Session has no slot "minutez"`, `no slot "bogus"`, `best_per slot "whoever"`} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("missing %q in:\n%v", want, err)
		}
	}
}
