// A neutral fixture: a shared recipe library. Recipes carry labels (which
// nest: Baking → Bread), can be found by label, cooked (a Meal links to the
// recipe) or copied, and every use is logged with the labels searched for.
const librarySchema = `
enums:
  Visibility: {values: [private, public], default: private}
  PickKind: {values: [cooked, copied]}
classes:
  Cook:
    display: name
    auth: {login: email, password: pw}
    access: {owner: id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: email, type: string, required: true, hidden: true}
      - {name: pw, type: password, required: true}
      - {name: name, type: string, required: true}
  Label:
    display: name
    access: {owner: created_by, read: public}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: created_by, type: integer}
      - {name: parent_id, type: integer}
      - {name: name, type: string, required: true}
    relationships:
      belongs_to:
        - {target: Label, via: parent_id, on_delete: cascade}
  Recipe:
    display: title
    search: false
    access: {owner: cook_id, read: owner, public_when: {visibility: public}}
    filters:
      - {via: labels, slot: label_id, include_children: parent_id, rank_by_usage: true}
    actions:
      - name: copy
        copy: [steps, labels]
        set: {based_on_id: source.id, visibility: "'private'", title: "source.title + ' (copy)'"}
    usage:
      log: Pick
      via: recipe_id
      kind: kind
      filter: label
      values: searched
      uses:
        - {kind: cooked, link: Meal.recipe_id, record: meal_id}
        - {kind: copied, action: copy, record: copy_id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: cook_id, type: integer, required: true}
      - {name: title, type: string, required: true}
      - {name: visibility, type: enum, enum: Visibility, default: private}
      - {name: based_on_id, type: integer}
    relationships:
      belongs_to:
        - {target: Cook, via: cook_id, on_delete: cascade}
        - {target: Recipe, via: based_on_id, on_delete: set_null, link: readable}
      has_many:
        - {target: Step, via: recipe_id, name: steps, order_by: "n asc"}
        - {target: RecipeLabel, via: recipe_id, name: labels}
  RecipeLabel:
    access: {parent: recipe_id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: recipe_id, type: integer, required: true}
      - {name: label_id, type: integer, required: true}
    relationships:
      belongs_to:
        - {target: Recipe, via: recipe_id, on_delete: cascade}
        - {target: Label, via: label_id, on_delete: cascade, link: readable}
  Step:
    access: {parent: recipe_id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: recipe_id, type: integer, required: true}
      - {name: n, type: integer, required: true}
      - {name: text, type: string}
    relationships:
      belongs_to: [{target: Recipe, via: recipe_id, on_delete: cascade}]
  Meal:
    access: {owner: cook_id, read: owner}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: cook_id, type: integer, required: true}
      - {name: recipe_id, type: integer}
      - {name: day, type: date, required: true}
    relationships:
      belongs_to:
        - {target: Cook, via: cook_id, on_delete: cascade}
        - {target: Recipe, via: recipe_id, on_delete: set_null, link: readable}
  Pick:
    access: {owner: cook_id, read: owner, write: nobody}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: cook_id, type: integer, required: true}
      - {name: recipe_id, type: integer, required: true}
      - {name: kind, type: enum, enum: PickKind, required: true}
      - {name: meal_id, type: integer}
      - {name: copy_id, type: integer}
    relationships:
      belongs_to:
        - {target: Cook, via: cook_id, on_delete: cascade}
        - {target: Recipe, via: recipe_id, on_delete: cascade}
        - {target: Meal, via: meal_id, on_delete: set_null}
        - {target: Recipe, via: copy_id, on_delete: set_null}
      has_many:
        - {target: PickLabel, via: pick_id, name: searched}
  PickLabel:
    access: {parent: pick_id}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: pick_id, type: integer, required: true}
      - {name: label_id, type: integer, required: true}
    relationships:
      belongs_to:
        - {target: Pick, via: pick_id, on_delete: cascade}
        - {target: Label, via: label_id, on_delete: cascade}
`

func titles(recs []*runtime.Record) string {
	var out []string
	for _, r := range recs {
		out = append(out, r.String("title"))
	}
	return strings.Join(out, ",")
}

func TestLibrary(t *testing.T) {
	m := mustLoad(t, librarySchema)
	for name, reg := range backends(t, m) {
		t.Run(name, func(t *testing.T) {
			cooks, labels, recipes := reg.MustClass("Cook"), reg.MustClass("Label"), reg.MustClass("Recipe")
			links, steps, picks := reg.MustClass("RecipeLabel"), reg.MustClass("Step"), reg.MustClass("Pick")
			var p [3]*runtime.Principal
			for i, n := range []string{"ann", "ben", "cat"} {
				c := cooks.New(map[string]any{"email": n + "@x.org", "pw": "password!1", "name": n})
				if err := cooks.Save(ctx, c); err != nil {
					t.Fatal(err)
				}
				p[i] = runtime.PrincipalFor(c)
			}
			label := func(name string, parent int64) int64 {
				l := labels.New(map[string]any{"name": name})
				if parent != 0 {
					l.Values["parent_id"] = parent
				}
				if err := labels.Save(ctx, l); err != nil {
					t.Fatal(err)
				}
				return l.ID()
			}
			baking := label("Baking", 0)
			bread := label("Bread", baking)
			quick := label("Quick", 0)
			recipe := func(title string, vis string, ls ...int64) *runtime.Record {
				r := recipes.New(map[string]any{"cook_id": p[0].ID, "title": title, "visibility": vis})
				if err := recipes.Save(ctx, r); err != nil {
					t.Fatal(err)
				}
				for _, l := range ls {
					links.Save(ctx, links.New(map[string]any{"recipe_id": r.ID(), "label_id": l}))
				}
				return r
			}
			sourdough := recipe("Sourdough", "public", bread)
			scones := recipe("Scones", "public", baking, quick)
			flatbread := recipe("Flatbread", "public", bread, quick)
			recipe("Secret", "private", baking)
			steps.Save(ctx, steps.New(map[string]any{"recipe_id": sourdough.ID(), "n": int64(1), "text": "Feed starter"}))
			steps.Save(ctx, steps.New(map[string]any{"recipe_id": sourdough.ID(), "n": int64(2), "text": "Bake"}))

			if !recipes.Class.NoSearch || labels.Class.NoSearch {
				t.Error("search: false should set NoSearch on Recipe only")
			}
			f := recipes.Class.FilterByName("label")
			find := func(pr *runtime.Principal, ids ...int64) string {
				conds, err := recipes.FilterConds(ctx, f, ids)
				if err != nil {
					t.Fatal(err)
				}
				q, ok := recipes.Scope(runtime.Query{Where: conds, OrderBy: "title asc"}, pr)
				if !ok {
					t.Fatal("not readable")
				}
				recs, err := recipes.List(ctx, q)
				if err != nil {
					t.Fatal(err)
				}
				return titles(recs)
			}
			// A parent label matches its descendants; all labels must match; private stays private.
			if got := find(p[1], baking); got != "Flatbread,Scones,Sourdough" {
				t.Errorf("baking (with bread below it): %s", got)
			}
			if got := find(p[1], bread, quick); got != "Flatbread" {
				t.Errorf("bread AND quick: %s", got)
			}
			if got := find(p[0], baking); got != "Flatbread,Scones,Secret,Sourdough" {
				t.Errorf("owner sees own private recipe: %s", got)
			}

			// Copy: values, set expressions, children; owned by the copier.
			act := recipes.Class.ActionByName("copy")
			cp, err := reg.Copy(ctx, p[1], sourdough, act, nil)
			if err != nil {
				t.Fatal(err)
			}
			if cp.Int("cook_id") != p[1].ID || cp.Int("based_on_id") != sourdough.ID() || cp.String("visibility") != "private" || cp.String("title") != "Sourdough (copy)" {
				t.Errorf("copy values: %v", cp.Values)
			}
			ks, _ := recipes.Children(ctx, cp, "steps", runtime.Query{})
			ls, _ := recipes.Children(ctx, cp, "labels", runtime.Query{})
			if len(ks) != 2 || ks[1].String("text") != "Bake" || len(ls) != 1 || ls[0].Int("label_id") != bread {
				t.Errorf("copied children: %d steps, %d labels", len(ks), len(ls))
			}
			// A failing check aborts and removes the partial copy.
			before, _ := recipes.Count(ctx, runtime.Query{})
			_, err = reg.Copy(ctx, p[1], sourdough, act, func(r *runtime.Record) error {
				if r.Class.Name == "Step" {
					return runtime.FieldErrors{"text": "no"}
				}
				return nil
			})
			after, _ := recipes.Count(ctx, runtime.Query{})
			if err == nil || after != before {
				t.Errorf("failed copy: err=%v, recipes %d → %d", err, before, after)
			}

			// Usage: Flatbread is chosen by two cooks searching "bread"; Scones by
			// one searching "bread, quick" and by one with no search at all.
			use := func(pr *runtime.Principal, r *runtime.Record, kind string, searched ...int64) {
				u := recipes.Class.Usage.Uses[0]
				if kind == "copied" {
					u = recipes.Class.Usage.Uses[1]
				}
				if err := reg.LogUsage(ctx, pr, recipes.Class, r.ID(), &u, 0, searched); err != nil {
					t.Fatal(err)
				}
			}
			use(p[1], flatbread, "cooked", bread)
			use(p[2], flatbread, "copied", bread)
			use(p[2], flatbread, "cooked", bread) // same cook again: still one person
			use(p[1], scones, "cooked", bread, quick)
			use(p[0], scones, "cooked")
			use(p[0], scones, "cooked")
			use(p[2], scones, "cooked")
			use(p[1], sourdough, "cooked", 999999) // unknown label: dropped
			ranked := func(ids ...int64) string {
				q, err := recipes.RankByUsage(runtime.Query{OrderBy: "title asc", Where: []runtime.Cond{runtime.Eq("visibility", "public")}}, ids)
				if err != nil {
					t.Fatal(err)
				}
				recs, err := recipes.List(ctx, q)
				if err != nil {
					t.Fatal(err)
				}
				return titles(recs)
			}
			// Overall: Scones 3 people, Flatbread 2, Sourdough 1.
			if got := ranked(); got != "Scones,Flatbread,Sourdough" {
				t.Errorf("overall ranking: %s", got)
			}
			// Searching exactly "bread": Flatbread's 2 exact picks beat Scones' 0 exact.
			if got := ranked(bread); got != "Flatbread,Scones,Sourdough" {
				t.Errorf("ranking for bread: %s", got)
			}
			// Searching "bread, quick": Scones was picked with exactly that set.
			if got := ranked(bread, quick); got != "Scones,Flatbread,Sourdough" {
				t.Errorf("ranking for bread+quick: %s", got)
			}
			if n, _ := picks.Count(ctx, runtime.Query{}); n != 8 {
				t.Errorf("picks logged: %d", n)
			}
			if runtime.CanCreate(picks.Class, p[0]) {
				t.Error("usage log must not be writable by people")
			}
		})
	}
}

func TestLibraryValidation(t *testing.T) {
	bad := strings.NewReplacer(
		`{via: labels, slot: label_id, include_children: parent_id, rank_by_usage: true}`, `{via: nope, slot: label_id}`,
		`copy: [steps, labels]`, `copy: [steps, steps.bogus]`,
		`{kind: copied, action: copy, record: copy_id}`, `{kind: eaten, action: nothing, record: copy_id}`,
		`via: recipe_id
      kind: kind`, `via: cook_id
      kind: kind`,
	).Replace(librarySchema)
	_, err := loadErr(bad)
	if err == nil {
		t.Fatal("expected validation errors")
	}
	for _, want := range []string{`via "nope" is not a has_many`, `"bogus" is not a has_many of Step`, `kind "eaten" is not a value`, `action "nothing" is not one of`, `via "cook_id" is not a belongs_to FK from Pick to Recipe`} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("missing %q in:\n%v", want, err)
		}
	}
	if _, err := loadErr(strings.Replace(librarySchema, "link: readable", "link: anything", 1)); err == nil || !strings.Contains(err.Error(), "link must be own or readable") {
		t.Errorf("bad link value: %v", err)
	}
}
