// A neutral fixture: a garden plan. A Bed is indoor or outdoor; its soil
// choices depend on that (options), its crop family must be one for its
// setting (match), and each Planting in it is spaced either by row or by
// grid (when / required_when), with options read through the link to its bed.
const rulesSchema = `
enums:
  Setting: {values: [indoor, outdoor]}
  Soil:
    values: [potting_mix, hydro, loam, clay]
    labels: {hydro: "Hydroponic"}
  Spacing: {values: [rows, grid]}
  Light: {values: [lamp, sun, shade]}
classes:
  Family:
    title: "name + ' (' + setting + ')'"
    display: name
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: name, type: string, required: true}
      - {name: setting, type: enum, enum: Setting, required: true}
  Bed:
    display: name
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: name, type: string, required: true}
      - {name: setting, type: enum, enum: Setting}
      - name: soil
        type: enum
        enum: Soil
        options:
          - {when: "setting == 'indoor'", values: [potting_mix, hydro]}
          - {when: "setting == 'outdoor'", values: [loam, clay]}
      - {name: family_id, type: integer}
    relationships:
      belongs_to:
        - {target: Family, via: family_id, match: {setting: setting}}
  Planting:
    checks:
      - {check: "seeds != null or plants != null", message: "Give seeds or plants"}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: bed_id, type: integer, required: true}
      - {name: seeds, type: integer}
      - {name: plants, type: integer}
      - {name: spacing, type: enum, enum: Spacing}
      - {name: row_cm, type: integer, when: "spacing == 'rows'", required_when: "spacing == 'rows'"}
      - {name: grid_cm, type: integer, when: "spacing == 'grid'", required_when: "spacing == 'grid'"}
      - name: light
        type: enum
        enum: Light
        options:
          - {when: "bed.setting == 'indoor'", values: [lamp]}
          - {when: "bed_id.setting == 'outdoor'", values: [sun, shade]}
    relationships:
      belongs_to:
        - {target: Bed, via: bed_id, on_delete: cascade}
`

func TestRules(t *testing.T) {
	m := mustLoad(t, rulesSchema)
	for name, reg := range backends(t, m) {
		t.Run(name, func(t *testing.T) {
			fams, beds, plants := reg.MustClass("Family"), reg.MustClass("Bed"), reg.MustClass("Planting")
			herbs := fams.New(map[string]any{"name": "Herbs", "setting": "indoor"})
			roots := fams.New(map[string]any{"name": "Roots", "setting": "outdoor"})
			for _, f := range []*runtime.Record{herbs, roots} {
				if err := fams.Save(ctx, f); err != nil {
					t.Fatal(err)
				}
			}
			if herbs.Title() != "Herbs (indoor)" {
				t.Errorf("title expression: %q", herbs.Title())
			}
			if got := runtime.DisplayValue(m.Class("Bed").Slot("soil"), "hydro"); got != "Hydroponic" {
				t.Errorf("enum label: %q", got)
			}
			if got := runtime.DisplayValue(m.Class("Bed").Slot("soil"), "potting_mix"); got != "Potting mix" {
				t.Errorf("enum default label: %q", got)
			}

			// options on own slots, and match against the target's slot
			bed := beds.New(map[string]any{"name": "Sill", "setting": "indoor", "soil": "loam", "family_id": roots.ID()})
			fe := fieldErrs(t, beds.Save(ctx, bed))
			if !strings.Contains(fe["soil"], "Potting mix, Hydroponic") || !strings.Contains(fe["family_id"], "setting") {
				t.Errorf("indoor bed with loam and an outdoor family: %v", fe)
			}
			bed.Values["soil"], bed.Values["family_id"] = "hydro", herbs.ID()
			if err := beds.Save(ctx, bed); err != nil {
				t.Fatal(err)
			}
			conds := reg.MatchConds(ctx, bed, m.Class("Bed").BelongsToVia("family_id"))
			if n, _ := fams.Count(ctx, runtime.Query{Where: conds}); n != 1 {
				t.Errorf("match should leave 1 family to pick, got %d", n)
			}
			if c := reg.MatchConds(ctx, beds.New(nil), m.Class("Bed").BelongsToVia("family_id")); len(c) != 0 {
				t.Error("no setting chosen yet: match adds no condition")
			}

			// when clears, required_when requires; options read through the link; checks
			p := plants.New(map[string]any{"bed_id": bed.ID(), "spacing": "rows", "grid_cm": int64(20), "light": "sun"})
			fe = fieldErrs(t, plants.Save(ctx, p))
			if fe["row_cm"] != "is required" || !strings.Contains(fe["light"], "Lamp") || fe[""] != "Give seeds or plants" {
				t.Errorf("planting rules: %v", fe)
			}
			if p.Values["grid_cm"] != nil {
				t.Error("grid_cm should be cleared when spacing is rows")
			}
			p.Values["row_cm"], p.Values["light"], p.Values["seeds"] = int64(30), "lamp", int64(12)
			if err := plants.Save(ctx, p); err != nil {
				t.Fatal(err)
			}
			if got := reg.AllowedValues(ctx, p, m.Class("Planting").Slot("light")); len(got) != 1 || got[0] != "lamp" {
				t.Errorf("allowed light via bed: %v", got)
			}
			if runtime.SlotApplies(p, m.Class("Planting").Slot("grid_cm")) {
				t.Error("grid_cm does not apply to row spacing")
			}
		})
	}
}

func TestRulesValidation(t *testing.T) {
	bad := strings.NewReplacer(
		`values: [potting_mix, hydro]}`, `values: [potting_mix, gravel]}`,
		`match: {setting: setting}`, `match: {colour: setting}`,
		`when: "spacing == 'rows'", required`, `when: "bed.setting == 'rows'", required`,
		`bed_id.setting ==`, `bed_id.nope ==`,
	).Replace(rulesSchema)
	_, err := schema.Load(schema.String(bad))
	if err == nil {
		t.Fatal("expected validation errors")
	}
	for _, want := range []string{`"gravel" is not a value of Soil`, `Family has no slot "colour"`,
		`unknown prefix "bed"`, `Bed has no slot "nope"`} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("missing %q in:\n%v", want, err)
		}
	}
	if _, err := schema.Load(schema.String(strings.Replace(rulesSchema, `hydro: "Hydroponic"`, `sand: "Sand"`, 1))); err == nil ||
		!strings.Contains(err.Error(), `unknown value "sand"`) {
		t.Errorf("label for unknown enum value: %v", err)
	}
}

func fieldErrs(t *testing.T, err error) runtime.FieldErrors {
	t.Helper()
	var fe runtime.FieldErrors
	if !errors.As(err, &fe) {
		t.Fatalf("want field errors, got %v", err)
	}
	return fe
}
