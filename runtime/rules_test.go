// A neutral fixture: a garden plan. A Bed is indoor or outdoor; its soil
// choices depend on that (options), its crop family must be one for its
// setting (match), and each Planting in it is spaced either by row or by
// grid (when / required_when), with options read through the link to its bed.
const rulesSchema = `
enums:
  Setting: {values: [indoor, outdoor]}
  Soil:
    values: [potting_mix, hydro, loam, clay]
    labels: {hydro: "Hydroponic"}
  Spacing: {values: [rows, grid]}
  Light: {values: [lamp, sun, shade]}
classes:
  Family:
    title: "name + ' (' + setting + ')'"
    display: name
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: name, type: string, required: true}
      - {name: setting, type: enum, enum: Setting, required: true}
  Bed:
    display: name
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: name, type: string, required: true}
      - {name: setting, type: enum, enum: Setting}
      - name: soil
        type: enum
        enum: Soil
        options:
          - {when: "setting == 'indoor'", values: [potting_mix, hydro]}
          - {when: "setting == 'outdoor'", values: [loam, clay]}
      - {name: family_id, type: integer}
    relationships:
      belongs_to:
        - {target: Family, via: family_id, match: {setting: setting}}
  Planting:
    checks:
      - {check: "seeds != null or plants != null", message: "Give seeds or plants"}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: bed_id, type: integer, required: true}
      - {name: n, type: integer, required: true, min: 1, sequence: {within: bed_id}}
      - {name: seeds, type: integer}
      - {name: plants, type: integer}
      - {name: spacing, type: enum, enum: Spacing, default_expr: "if(bed.setting == 'indoor', 'grid', 'rows')"}
      - {name: row_cm, type: integer, when: "spacing == 'rows'", required_when: "spacing == 'rows'"}
      - {name: grid_cm, type: integer, when: "spacing == 'grid'", required_when: "spacing == 'grid'"}
      - name: light
        type: enum
        enum: Light
        options:
          - {when: "bed.setting == 'indoor'", values: [lamp]}
          - {when: "bed_id.setting == 'outdoor'", values: [sun, shade]}
    relationships:
      belongs_to:
        - {target: Bed, via: bed_id, on_delete: cascade}
`

func TestRules(t *testing.T) {
	m := mustLoad(t, rulesSchema)
	for name, reg := range backends(t, m) {
		t.Run(name, func(t *testing.T) {
			fams, beds, plants := reg.MustClass("Family"), reg.MustClass("Bed"), reg.MustClass("Planting")
			herbs := fams.New(map[string]any{"name": "Herbs", "setting": "indoor"})
			roots := fams.New(map[string]any{"name": "Roots", "setting": "outdoor"})
			for _, f := range []*runtime.Record{herbs, roots} {
				if err := fams.Save(ctx, f); err != nil {
					t.Fatal(err)
				}
			}
			if herbs.Title() != "Herbs (indoor)" {
				t.Errorf("title expression: %q", herbs.Title())
			}
			if got := runtime.DisplayValue(m.Class("Bed").Slot("soil"), "hydro"); got != "Hydroponic" {
				t.Errorf("enum label: %q", got)
			}
			if got := runtime.DisplayValue(m.Class("Bed").Slot("soil"), "potting_mix"); got != "Potting mix" {
				t.Errorf("enum default label: %q", got)
			}

			// options on own slots, and match against the target's slot
			bed := beds.New(map[string]any{"name": "Sill", "setting": "indoor", "soil": "loam", "family_id": roots.ID()})
			fe := fieldErrs(t, beds.Save(ctx, bed))
			if !strings.Contains(fe["soil"], "Potting mix, Hydroponic") || !strings.Contains(fe["family_id"], "setting") {
				t.Errorf("indoor bed with loam and an outdoor family: %v", fe)
			}
			bed.Values["soil"], bed.Values["family_id"] = "hydro", herbs.ID()
			if err := beds.Save(ctx, bed); err != nil {
				t.Fatal(err)
			}
			conds := reg.MatchConds(ctx, bed, m.Class("Bed").BelongsToVia("family_id"))
			if n, _ := fams.Count(ctx, runtime.Query{Where: conds}); n != 1 {
				t.Errorf("match should leave 1 family to pick, got %d", n)
			}
			if c := reg.MatchConds(ctx, beds.New(nil), m.Class("Bed").BelongsToVia("family_id")); len(c) != 0 {
				t.Error("no setting chosen yet: match adds no condition")
			}

			// when clears, required_when requires; options read through the link; checks
			p := plants.New(map[string]any{"bed_id": bed.ID(), "spacing": "rows", "grid_cm": int64(20), "light": "sun"})
			fe = fieldErrs(t, plants.Save(ctx, p))
			if fe["row_cm"] != "is required" || !strings.Contains(fe["light"], "Lamp") || fe[""] != "Give seeds or plants" {
				t.Errorf("planting rules: %v", fe)
			}
			if p.Values["grid_cm"] != nil {
				t.Error("grid_cm should be cleared when spacing is rows")
			}
			p.Values["row_cm"], p.Values["light"], p.Values["seeds"] = int64(30), "lamp", int64(12)
			if err := plants.Save(ctx, p); err != nil {
				t.Fatal(err)
			}
			if got := reg.AllowedValues(ctx, p, m.Class("Planting").Slot("light")); len(got) != 1 || got[0] != "lamp" {
				t.Errorf("allowed light via bed: %v", got)
			}
			if runtime.SlotApplies(p, m.Class("Planting").Slot("grid_cm")) {
				t.Error("grid_cm does not apply to row spacing")
			}

			// sequence: numbered within the bed, unique, next free number by default
			if p.Int("n") != 1 {
				t.Errorf("first planting should be numbered 1, got %v", p.Values["n"])
			}
			p2 := plants.New(map[string]any{"bed_id": bed.ID(), "seeds": int64(3), "grid_cm": int64(10)})
			if err := plants.Save(ctx, p2); err != nil || p2.Int("n") != 2 {
				t.Fatalf("second planting: %v n=%v", err, p2.Values["n"])
			}
			p3 := plants.New(map[string]any{"bed_id": bed.ID(), "seeds": int64(3), "n": int64(1), "grid_cm": int64(10)})
			if err := plants.Save(ctx, p3); err != nil || p3.Int("n") != 3 {
				t.Errorf("a new row always takes the next number: %v n=%v", err, p3.Values["n"])
			}
			if err := plants.Save(ctx, p2); err != nil || p2.Int("n") != 2 {
				t.Errorf("re-saving keeps its own number: %v n=%v", err, p2.Values["n"])
			}
			if p2.Assign(map[string]any{"n": "9"}) != nil || p2.Values["n"] != int64(2) {
				t.Error("clients cannot set a sequence number")
			}
			bed2 := beds.New(map[string]any{"name": "Shelf", "setting": "indoor"})
			if err := beds.Save(ctx, bed2); err != nil {
				t.Fatal(err)
			}
			p2.Values["bed_id"] = bed2.ID()
			if err := plants.Save(ctx, p2); err != nil || p2.Int("n") != 1 {
				t.Errorf("moved to an empty bed: first there: %v n=%v", err, p2.Values["n"])
			}
			p3.Values["bed_id"] = bed2.ID()
			if err := plants.Save(ctx, p3); err != nil || p3.Int("n") != 2 {
				t.Errorf("moved: next there: %v n=%v", err, p3.Values["n"])
			}
			p.Values["bed_id"] = bed2.ID()
			if err := plants.Save(ctx, p); err != nil || p.Int("n") != 3 {
				t.Errorf("moved: next there: %v n=%v", err, p.Values["n"])
			}
			p4 := plants.New(map[string]any{"bed_id": bed2.ID(), "seeds": int64(1), "grid_cm": int64(10)})
			if err := plants.Save(ctx, p4); err != nil || p4.Int("n") != 4 {
				t.Errorf("next after 1,2,3: %v n=%v", err, p4.Values["n"])
			}
			p.Values["bed_id"] = bed.ID()
			if err := plants.Save(ctx, p); err != nil || p.Int("n") != 1 {
				t.Errorf("moved back: %v n=%v", err, p.Values["n"])
			}
			taken, err := reg.SequenceTaken(ctx, m.Class("Planting"), m.Class("Planting").Slot("n"), []int64{bed2.ID(), 999}, p4.ID())
			if err != nil || fmt.Sprint(taken[bed2.ID()]) != "[1 2]" || len(taken[999]) != 0 || runtime.SequenceNext(nil) != 1 {
				t.Errorf("taken: %v %v", taken, err)
			}
		})
	}
}

func TestRulesValidation(t *testing.T) {
	bad := strings.NewReplacer(
		`values: [potting_mix, hydro]}`, `values: [potting_mix, gravel]}`,
		`match: {setting: setting}`, `match: {colour: setting}`,
		`when: "spacing == 'rows'", required`, `when: "bed.colour == 'rows'", required`,
		`bed_id.setting ==`, `bed_id.nope ==`,
	).Replace(rulesSchema)
	_, err := schema.Load(schema.String(bad))
	if err == nil {
		t.Fatal("expected validation errors")
	}
	for _, want := range []string{`"gravel" is not a value of Soil`, `Family has no slot "colour"`,
		`Bed has no slot "colour"`, `Bed has no slot "nope"`} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("missing %q in:\n%v", want, err)
		}
	}
	if _, err := schema.Load(schema.String(strings.Replace(rulesSchema, `hydro: "Hydroponic"`, `sand: "Sand"`, 1))); err == nil ||
		!strings.Contains(err.Error(), `unknown value "sand"`) {
		t.Errorf("label for unknown enum value: %v", err)
	}
}

func fieldErrs(t *testing.T, err error) runtime.FieldErrors {
	t.Helper()
	var fe runtime.FieldErrors
	if !errors.As(err, &fe) {
		t.Fatalf("want field errors, got %v", err)
	}
	return fe
}

func TestSequenceConstraint(t *testing.T) {
	m := mustLoad(t, rulesSchema)
	found := false
	for _, k := range m.Class("Planting").Constraints {
		found = found || (k.IsUnique() && strings.Join(k.Columns, ",") == "bed_id,n")
	}
	if !found {
		t.Error("sequence should add a unique (bed_id, n) constraint")
	}
	bad := strings.Replace(rulesSchema, "sequence: {within: bed_id}", "sequence: {within: seeds}", 1)
	if _, err := schema.Load(schema.String(bad)); err == nil || !strings.Contains(err.Error(), `within "seeds" is not a belongs_to FK`) {
		t.Errorf("sequence within a non-FK: %v", err)
	}
}

func TestDefaultExpr(t *testing.T) {
	m := mustLoad(t, rulesSchema)
	for name, reg := range backends(t, m) {
		t.Run(name, func(t *testing.T) {
			beds, plants := reg.MustClass("Bed"), reg.MustClass("Planting")
			in, out := beds.New(map[string]any{"name": "In", "setting": "indoor"}), beds.New(map[string]any{"name": "Out", "setting": "outdoor"})
			beds.Save(ctx, in)
			beds.Save(ctx, out)
			p := plants.New(map[string]any{"bed_id": in.ID()})
			reg.ApplyDefaults(ctx, p)
			if p.Values["spacing"] != "grid" {
				t.Errorf("indoor default: %v", p.Values["spacing"])
			}
			q := plants.New(map[string]any{"bed_id": out.ID(), "seeds": int64(1), "row_cm": int64(30)})
			if err := plants.Save(ctx, q); err != nil || q.Values["spacing"] != "rows" {
				t.Errorf("save applies the default: %v %v", err, q.Values["spacing"])
			}
			r := plants.New(map[string]any{"bed_id": out.ID(), "seeds": int64(1), "spacing": "grid", "grid_cm": int64(20)})
			if err := plants.Save(ctx, r); err != nil || r.Values["spacing"] != "grid" {
				t.Errorf("a chosen value wins: %v %v", err, r.Values["spacing"])
			}
			q.Values["spacing"] = nil
			q.Values["row_cm"] = nil
			if err := plants.Save(ctx, q); err != nil || q.Values["spacing"] != nil {
				t.Errorf("defaults apply to new records only: %v %v", err, q.Values["spacing"])
			}
		})
	}
	if _, err := schema.Load(schema.String(strings.Replace(rulesSchema, "default_expr: \"if(bed.setting", "default_expr: \"if(bed.colour", 1))); err == nil {
		t.Error("default_expr should be checked")
	}
}

// TestWhenThroughLinks: a when rule may read the parent (light applies only
// to indoor beds); Save loads the link, and nothing is cleared on a guess
// when links were not loaded.
func TestWhenThroughLinks(t *testing.T) {
	m := mustLoad(t, strings.Replace(rulesSchema, "      - name: light\n", "      - name: light\n        when: \"bed.setting == 'indoor'\"\n", 1))
	reg := backends(t, m)["sqlite"]
	beds, plants := reg.MustClass("Bed"), reg.MustClass("Planting")
	in, out := beds.New(map[string]any{"name": "In", "setting": "indoor"}), beds.New(map[string]any{"name": "Out", "setting": "outdoor"})
	beds.Save(ctx, in)
	beds.Save(ctx, out)
	light := m.Class("Planting").Slot("light")
	p := plants.New(map[string]any{"bed_id": out.ID(), "seeds": int64(1), "light": "sun", "row_cm": int64(30)})
	if !runtime.SlotApplies(p, light) {
		t.Error("links not loaded: the rule must not hide the field on a guess")
	}
	if err := plants.Save(ctx, p); err != nil || p.Values["light"] != nil {
		t.Errorf("outdoor bed: light should be cleared: %v %v", err, p.Values["light"])
	}
	q := plants.New(map[string]any{"bed_id": in.ID(), "seeds": int64(1), "light": "lamp", "grid_cm": int64(20)})
	if err := plants.Save(ctx, q); err != nil || q.Values["light"] != "lamp" {
		t.Errorf("indoor bed keeps light: %v %v", err, q.Values["light"])
	}
	reg.LoadLinks(ctx, p)
	if runtime.SlotApplies(p, light) {
		t.Error("loaded links: light does not apply outdoors")
	}
}

// TestLabelWhen: class and slot labels that depend on the record, through
// its links (a planting is a "Cutting" in an indoor bed).
func TestLabelWhen(t *testing.T) {
	m := mustLoad(t, strings.Replace(strings.Replace(rulesSchema,
		"  Planting:\n", "  Planting:\n    label: Planting\n    label_when: [{when: \"bed.setting == 'indoor'\", label: Cutting}]\n", 1),
		"      - {name: seeds, type: integer}", "      - {name: seeds, type: integer, label_when: [{when: \"bed.setting == 'indoor'\", label: Cuttings}]}", 1))
	reg := backends(t, m)["sqlite"]
	beds, plants := reg.MustClass("Bed"), reg.MustClass("Planting")
	in, out := beds.New(map[string]any{"name": "In", "setting": "indoor"}), beds.New(map[string]any{"name": "Out", "setting": "outdoor"})
	beds.Save(ctx, in)
	beds.Save(ctx, out)
	seeds := m.Class("Planting").Slot("seeds")
	pin, pout := plants.New(map[string]any{"bed_id": in.ID()}), plants.New(map[string]any{"bed_id": out.ID()})
	if got := reg.ClassLabel(ctx, pin); got != "Cutting" {
		t.Errorf("indoor class label: %q", got)
	}
	if got := reg.ClassLabel(ctx, pout); got != "Planting" {
		t.Errorf("outdoor class label: %q", got)
	}
	if reg.SlotLabel(ctx, pin, seeds) != "Cuttings" || reg.SlotLabel(ctx, pout, seeds) != "Seeds" {
		t.Errorf("slot labels: %q %q", reg.SlotLabel(ctx, pin, seeds), reg.SlotLabel(ctx, pout, seeds))
	}
	if _, err := schema.Load(schema.String(strings.Replace(rulesSchema, "  Planting:\n", "  Planting:\n    label_when: [{when: \"bed.colour == 1\", label: X}]\n", 1))); err == nil {
		t.Error("label_when expressions are checked")
	}
}
