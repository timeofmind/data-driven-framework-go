package runtime_test

import (
	"strings"
	"testing"

	"github.com/timeofmind/data-driven-framework-go/runtime"
	"github.com/timeofmind/data-driven-framework-go/schema"
)

// A plan's sessions move with its start date (on_change), and copying a plan
// keeps the dates but starts every session afresh (set_children).
const planSchema = `
enums:
  State: {values: [planned, done], default: planned}
classes:
  Plan:
    display: name
    on_change:
      - slot: start_date
        set: {end_date: "add_days(old.end_date, days_between(old.start_date, start_date))"}
        children:
          sessions: {day: "add_days(child.day, days_between(old.start_date, start_date))"}
    actions:
      - name: copy
        copy: [sessions]
        copy_links: {sessions.drill_id: copy}
        set: {name: "source.name + ' (copy)'"}
        set_children:
          sessions: {state: "'planned'", note: "root.name"}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: name, type: string, required: true}
      - {name: start_date, type: date, required: true}
      - {name: end_date, type: date}
    relationships:
      has_many: [{target: Session, via: plan_id, name: sessions}]
  Session:
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: plan_id, type: integer, required: true}
      - {name: day, type: date, required: true}
      - {name: state, type: enum, enum: State}
      - {name: note, type: string}
      - {name: drill_id, type: integer}
    relationships:
      belongs_to:
        - {target: Plan, via: plan_id, on_delete: cascade}
        - {target: Drill, via: drill_id, on_delete: set_null}
  Drill:
    display: name
    actions:
      - name: copy
        when: "shared"
        copy: [steps]
        set: {name: "source.name + ' (copy)'", shared: "false"}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: name, type: string, required: true}
      - {name: shared, type: boolean}
    relationships:
      has_many: [{target: Step, via: drill_id, name: steps}]
  Step:
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: drill_id, type: integer, required: true}
      - {name: what, type: string}
    relationships:
      belongs_to: [{target: Drill, via: drill_id, on_delete: cascade}]
`

func TestOnChangeAndCopyChildren(t *testing.T) {
	m := mustLoad(t, planSchema)
	for name, reg := range backends(t, m) {
		t.Run(name, func(t *testing.T) {
			plans, sessions := reg.MustClass("Plan"), reg.MustClass("Session")
			p := plans.New(map[string]any{"name": "Winter", "start_date": "2026-11-02", "end_date": "2026-12-27"})
			if err := plans.Save(ctx, p); err != nil {
				t.Fatal(err)
			}
			drills, steps := reg.MustClass("Drill"), reg.MustClass("Step")
			drill := drills.New(map[string]any{"name": "Hills", "shared": false}) // private: its own copy action would not run
			if err := drills.Save(ctx, drill); err != nil {
				t.Fatal(err)
			}
			steps.Save(ctx, steps.New(map[string]any{"drill_id": drill.ID(), "what": "8 × 30 s up"}))
			for _, d := range []string{"2026-11-03", "2026-11-28"} {
				if err := sessions.Save(ctx, sessions.New(map[string]any{"plan_id": p.ID(), "day": d, "state": "done", "drill_id": drill.ID()})); err != nil {
					t.Fatal(err)
				}
			}
			days := func(plan *runtime.Record) string {
				kids, _ := plans.Children(ctx, plan, "sessions", runtime.Query{OrderBy: "day asc"})
				var out []string
				for _, k := range kids {
					out = append(out, k.String("day")+"/"+k.String("state")+"/"+k.String("note"))
				}
				return strings.Join(out, " ")
			}
			cp, err := reg.Copy(ctx, nil, p, m.Class("Plan").ActionByName("copy"), nil)
			if err != nil {
				t.Fatal(err)
			}
			if cp.String("start_date") != "2026-11-02" || days(cp) != "2026-11-03/planned/Winter 2026-11-28/planned/Winter" {
				t.Errorf("copy keeps dates and resets sessions: %v %s", cp.Values, days(cp))
			}
			// copy_links: the drill both sessions use is copied once, in full, and linked.
			if n, _ := drills.Count(ctx, runtime.Query{}); n != 2 {
				t.Errorf("one drill copy expected, have %d drills", n)
			}
			kids, _ := plans.Children(ctx, cp, "sessions", runtime.Query{})
			if len(kids) != 2 || kids[0].Int("drill_id") == drill.ID() || kids[0].Int("drill_id") != kids[1].Int("drill_id") {
				t.Fatalf("sessions should share the new drill copy: %v", kids)
			}
			dc, _ := drills.Load(ctx, kids[0].Int("drill_id"))
			if dc.String("name") != "Hills (copy)" {
				t.Errorf("the drill copy runs the drill's own copy action: %v", dc.Values)
			}
			if n, _ := steps.Count(ctx, runtime.Query{Where: []runtime.Cond{runtime.Eq("drill_id", dc.ID())}}); n != 1 {
				t.Errorf("the drill is copied in full: %d steps", n)
			}
			cp.Values["start_date"] = "2027-01-04" // +63 days
			if err := plans.Save(ctx, cp); err != nil {
				t.Fatal(err)
			}
			if cp.String("end_date") != "2027-02-28" || days(cp) != "2027-01-05/planned/Winter 2027-01-30/planned/Winter" {
				t.Errorf("moving the start moves the end and every session: %v %s", cp.Values, days(cp))
			}
			if days(p) != "2026-11-03/done/ 2026-11-28/done/" {
				t.Errorf("the original is untouched: %s", days(p))
			}
			cp.Values["name"] = "Renamed"
			if err := plans.Save(ctx, cp); err != nil || days(cp) != "2027-01-05/planned/Winter 2027-01-30/planned/Winter" {
				t.Errorf("other edits move nothing: %v %s", err, days(cp))
			}
		})
	}
	bad := strings.Replace(planSchema, "child.day, days_between", "child.when, days_between", 1)
	if _, err := schema.Load(schema.String(bad)); err == nil || !strings.Contains(err.Error(), `Session has no slot "when"`) {
		t.Errorf("on_change child expressions are checked: %v", err)
	}
	bad = strings.Replace(planSchema, "sessions.drill_id: copy", "sessions.drill_id: clone", 1)
	if _, err := schema.Load(schema.String(bad)); err == nil || !strings.Contains(err.Error(), `Drill has no action "clone"`) {
		t.Errorf("copy_links actions are checked: %v", err)
	}
	bad = strings.Replace(planSchema, "sessions: {state:", "talks: {state:", 1)
	if _, err := schema.Load(schema.String(bad)); err == nil || !strings.Contains(err.Error(), `set_children "talks" is not one of the copy paths`) {
		t.Errorf("set_children paths are checked: %v", err)
	}
}
