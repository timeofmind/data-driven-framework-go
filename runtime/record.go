// Package runtime gives typed, validated data access to the classes of a
// model.Model over database/sql. Where the Perl framework generated one Perl
// package per class, Go uses one generic Record type and a per-class handle.
package runtime

import (
	"encoding/json"
	"fmt"
	"math"
	"strconv"
	"strings"
	"time"

	"github.com/timeofmind/data-driven-framework-go/model"
)

// Record is one row of a class. Values are keyed by slot name and hold
// normalised Go values: int64, float64, bool, string, or nil.
type Record struct {
	Class     *model.Class
	Values    map[string]any
	persisted bool
}

// NewRecord creates an unsaved record with schema defaults applied, then the
// given values (which are not coerced; use Set or Assign for untrusted input).
func NewRecord(c *model.Class, values map[string]any) *Record {
	r := &Record{Class: c, Values: map[string]any{}}
	for _, s := range c.AllSlots() {
		if s.Default != nil && !s.Autogenerated {
			v, err := Coerce(s, *s.Default)
			if err == nil {
				r.Values[s.Name] = v
			}
		}
	}
	for k, v := range values {
		r.Values[k] = v
	}
	return r
}

func (r *Record) Persisted() bool { return r.persisted }

// ID returns the primary key value, or 0 when unsaved.
func (r *Record) ID() int64 {
	pk := r.Class.PKSlot()
	if pk == nil {
		return 0
	}
	n, _ := r.Values[pk.Name].(int64)
	return n
}

func (r *Record) Get(name string) any { return r.Values[name] }

// String returns a slot value formatted for display ("" for nil).
func (r *Record) String(name string) string { return FormatValue(r.Values[name]) }

func (r *Record) Int(name string) int64 {
	switch v := r.Values[name].(type) {
	case int64:
		return v
	case float64:
		return int64(v)
	}
	return 0
}

func (r *Record) Float(name string) float64 {
	switch v := r.Values[name].(type) {
	case float64:
		return v
	case int64:
		return float64(v)
	}
	return 0
}

func (r *Record) Bool(name string) bool { b, _ := r.Values[name].(bool); return b }

// Set coerces and stores one value. Unknown slots are an error.
func (r *Record) Set(name string, raw any) error {
	s := r.Class.Slot(name)
	if s == nil {
		return fmt.Errorf("%s has no field %q", r.Class.Name, name)
	}
	v, err := Coerce(s, raw)
	if err != nil {
		return err
	}
	r.Values[name] = v
	return nil
}

// Title returns the record's display text (its display slot, else "#id").
func (r *Record) Title() string {
	if s := r.Class.DisplaySlot(); s != nil {
		if t := r.String(s.Name); t != "" && s != r.Class.PKSlot() {
			return t
		}
	}
	return fmt.Sprintf("#%d", r.ID())
}

// Public returns the values safe to expose: hidden and password slots removed.
func (r *Record) Public() map[string]any {
	out := map[string]any{}
	for _, s := range r.Class.AllSlots() {
		if s.Hidden || s.Type == "password" {
			continue
		}
		out[s.Name] = r.Values[s.Name]
	}
	return out
}

// MarshalJSON encodes Public().
func (r *Record) MarshalJSON() ([]byte, error) { return json.Marshal(r.Public()) }

// FieldErrors maps slot names to human-readable problems.
type FieldErrors map[string]string

func (e FieldErrors) Error() string {
	var parts []string
	for k, v := range e {
		parts = append(parts, k+": "+v)
	}
	return "validation failed: " + strings.Join(parts, "; ")
}

// Assign coerces untrusted input (form or JSON) onto the record. Only writable
// slots are touched; the names in skip (e.g. an access owner slot) are ignored.
// Absent keys leave values unchanged. Problems are returned per field.
func (r *Record) Assign(input map[string]any, skip ...string) FieldErrors {
	errs := FieldErrors{}
	skipped := map[string]bool{}
	for _, n := range skip {
		skipped[n] = true
	}
	for _, s := range r.Class.AllSlots() {
		if !s.Writable() || skipped[s.Name] {
			continue
		}
		raw, present := input[s.Name]
		if !present {
			continue
		}
		if s.Type == "password" {
			if str, _ := raw.(string); str == "" {
				continue // empty password field on an edit form means "keep"
			}
		}
		v, err := Coerce(s, raw)
		if err != nil {
			errs[s.Name] = err.Error()
			continue
		}
		r.Values[s.Name] = v
	}
	if len(errs) == 0 {
		return nil
	}
	return errs
}

// Validate checks required fields and slot rules (enum, min/max, pattern).
func (r *Record) Validate() FieldErrors {
	errs := FieldErrors{}
	for _, s := range r.Class.AllSlots() {
		if s.Autogenerated {
			continue
		}
		v := r.Values[s.Name]
		if v == nil || v == "" {
			if s.Required && s.Type != "boolean" {
				errs[s.Name] = "is required"
			}
			continue
		}
		if msg := checkSlot(s, v); msg != "" {
			errs[s.Name] = msg
		}
	}
	if len(errs) == 0 {
		return nil
	}
	return errs
}

func checkSlot(s *model.Slot, v any) string {
	switch s.Type {
	case "enum":
		if s.EnumObj != nil && !s.EnumObj.HasValue(fmt.Sprint(v)) {
			return "must be one of " + strings.Join(s.EnumObj.Values, ", ")
		}
	case "integer", "float":
		var f float64
		switch n := v.(type) {
		case int64:
			f = float64(n)
		case float64:
			f = n
		}
		if s.Min != nil && f < *s.Min {
			return fmt.Sprintf("must be at least %g", *s.Min)
		}
		if s.Max != nil && f > *s.Max {
			return fmt.Sprintf("must be at most %g", *s.Max)
		}
	case "string", "text", "password":
		str, _ := v.(string)
		if s.Type == "password" && strings.HasPrefix(str, bcryptPrefix) {
			return "" // already hashed
		}
		n := float64(len([]rune(str)))
		if s.Min != nil && n < *s.Min {
			return fmt.Sprintf("must be at least %g characters", *s.Min)
		}
		if s.Max != nil && n > *s.Max {
			return fmt.Sprintf("must be at most %g characters", *s.Max)
		}
		if re := s.PatternRE(); re != nil && !re.MatchString(str) {
			return "has an invalid format"
		}
	}
	return ""
}

const (
	dateLayout     = "2006-01-02"
	datetimeLayout = "2006-01-02 15:04:05"
)

var datetimeInputs = []string{
	datetimeLayout, "2006-01-02T15:04:05", "2006-01-02T15:04", "2006-01-02 15:04",
	time.RFC3339, time.RFC3339Nano, "2006-01-02T15:04:05Z",
}

// Coerce converts raw input (string from a form, JSON value, or DB value) to
// the slot's normalised Go type. Empty strings become nil.
func Coerce(s *model.Slot, raw any) (any, error) {
	if b, ok := raw.([]byte); ok {
		raw = string(b)
	}
	if raw == nil {
		return nil, nil
	}
	if str, ok := raw.(string); ok {
		str = strings.TrimSpace(str)
		if str == "" && s.Type != "string" && s.Type != "text" {
			return nil, nil
		}
		if str == "" {
			return nil, nil
		}
		raw = str
	}
	switch s.Type {
	case "integer":
		switch v := raw.(type) {
		case int64:
			return v, nil
		case int:
			return int64(v), nil
		case float64:
			if v != math.Trunc(v) {
				return nil, fmt.Errorf("must be a whole number")
			}
			return int64(v), nil
		case json.Number:
			n, err := v.Int64()
			if err != nil {
				return nil, fmt.Errorf("must be a whole number")
			}
			return n, nil
		case string:
			n, err := strconv.ParseInt(v, 10, 64)
			if err != nil {
				return nil, fmt.Errorf("must be a whole number")
			}
			return n, nil
		case bool:
			if v {
				return int64(1), nil
			}
			return int64(0), nil
		}
	case "float":
		switch v := raw.(type) {
		case float64:
			return v, nil
		case float32:
			return float64(v), nil
		case int64:
			return float64(v), nil
		case int:
			return float64(v), nil
		case json.Number:
			f, err := v.Float64()
			if err != nil {
				return nil, fmt.Errorf("must be a number")
			}
			return f, nil
		case string:
			f, err := strconv.ParseFloat(v, 64)
			if err != nil {
				return nil, fmt.Errorf("must be a number")
			}
			return f, nil
		}
	case "boolean":
		switch v := raw.(type) {
		case bool:
			return v, nil
		case int64:
			return v != 0, nil
		case int:
			return v != 0, nil
		case float64:
			return v != 0, nil
		case string:
			switch strings.ToLower(v) {
			case "1", "true", "on", "yes", "y":
				return true, nil
			case "0", "false", "off", "no", "n":
				return false, nil
			}
			return nil, fmt.Errorf("must be true or false")
		}
	case "date":
		switch v := raw.(type) {
		case time.Time:
			return v.Format(dateLayout), nil
		case string:
			if len(v) >= 10 {
				if t, err := time.Parse(dateLayout, v[:10]); err == nil {
					return t.Format(dateLayout), nil
				}
			}
			return nil, fmt.Errorf("must be a date (YYYY-MM-DD)")
		}
	case "datetime":
		switch v := raw.(type) {
		case time.Time:
			return v.Format(datetimeLayout), nil
		case string:
			for _, layout := range datetimeInputs {
				if t, err := time.Parse(layout, v); err == nil {
					return t.Format(datetimeLayout), nil
				}
			}
			return nil, fmt.Errorf("must be a date and time")
		}
	default: // string, text, enum, password
		switch v := raw.(type) {
		case string:
			return v, nil
		case float64, int64, int, bool, json.Number:
			return fmt.Sprint(v), nil
		}
	}
	return nil, fmt.Errorf("unsupported value %T", raw)
}

// FormatValue renders a normalised value for display or form input.
func FormatValue(v any) string {
	switch x := v.(type) {
	case nil:
		return ""
	case string:
		return x
	case int64:
		return strconv.FormatInt(x, 10)
	case float64:
		return strconv.FormatFloat(x, 'f', -1, 64)
	case bool:
		if x {
			return "1"
		}
		return "0"
	}
	return fmt.Sprint(v)
}
