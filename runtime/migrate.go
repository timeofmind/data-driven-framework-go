package runtime

import (
	"context"
	"fmt"
	"strings"

	"github.com/timeofmind/data-driven-framework-go/generator"
)

// EnsureResult reports what EnsureSchema changed.
type EnsureResult struct {
	CreatedTables []string
	AddedColumns  []string // "table.column"
	// Pending lists changes EnsureSchema will not make on its own (type,
	// nullability or default changes, dropped columns); generate a migration.
	Pending []string
}

// EnsureSchema brings the database up to the model without ever losing data:
// it creates missing tables (and the framework metadata tables), adds missing
// columns, and records the model hash when anything changed. Destructive or
// type-changing differences are reported in Pending and left alone.
func (r *Registry) EnsureSchema(ctx context.Context) (*EnsureResult, error) {
	res := &EnsureResult{}
	existing, err := r.tables(ctx)
	if err != nil {
		return nil, err
	}
	for _, stmt := range generator.SplitStatements(r.Dialect.MetadataTables()) {
		if _, err := r.DB.ExecContext(ctx, stmt); err != nil {
			return nil, fmt.Errorf("metadata tables: %w", err)
		}
	}
	for _, c := range r.Model.ConcreteClasses() {
		table := c.EffectiveTable()
		if !existing[table] {
			for _, stmt := range generator.SplitStatements(r.Dialect.CreateTable(c, r.Model)) {
				if _, err := r.DB.ExecContext(ctx, stmt); err != nil {
					return nil, fmt.Errorf("create %s: %w", table, err)
				}
			}
			res.CreatedTables = append(res.CreatedTables, table)
			continue
		}
		cols, err := r.columns(ctx, table)
		if err != nil {
			return nil, err
		}
		want := map[string]bool{}
		for _, seg := range chain(c)[len(chain(c))-1:] {
			for _, s := range seg.slots {
				want[s.Name] = true
				if cols[s.Name] {
					continue
				}
				def := r.Dialect.ColumnDef(s, r.Model)
				if s.Autogenerated && s.Type == "integer" {
					res.Pending = append(res.Pending, table+"."+s.Name+": cannot add a primary key column")
					continue
				}
				if r.Dialect.Name() == "sqlite" && s.Required && s.Default == nil && !s.Autogenerated {
					// SQLite refuses NOT NULL without a default; add as nullable.
					def = strings.Replace(def, " NOT NULL", "", 1)
				}
				if r.Dialect.Name() == "sqlite" && s.Autogenerated && s.Type == "datetime" {
					// SQLite cannot ADD COLUMN with a non-constant default.
					def = r.Dialect.Quote(s.Name) + " TEXT"
				}
				if _, err := r.DB.ExecContext(ctx, "ALTER TABLE "+r.Dialect.Quote(table)+" ADD COLUMN "+def); err != nil {
					return nil, fmt.Errorf("add column %s.%s: %w", table, s.Name, err)
				}
				res.AddedColumns = append(res.AddedColumns, table+"."+s.Name)
			}
		}
		if c.IsJoinedChild() {
			want[c.PKSlot().Name] = true
		}
		for col := range cols {
			if !want[col] {
				res.Pending = append(res.Pending, table+"."+col+": column not in schema (left in place)")
			}
		}
	}
	if len(res.CreatedTables)+len(res.AddedColumns) > 0 {
		if err := r.recordVersion(ctx, "ensure-schema"); err != nil {
			return nil, err
		}
	}
	return res, nil
}

func (r *Registry) recordVersion(ctx context.Context, note string) error {
	q := r.Dialect.Quote
	_, err := r.DB.ExecContext(ctx,
		"INSERT INTO "+q("_framework_schema_version")+" (schema_version, framework_version, model_hash, notes) VALUES (?, ?, ?, ?)",
		r.Model.SchemaVersion, generator.Version, r.Model.Hash(), note)
	return err
}

// AppliedHash returns the most recently recorded model hash ("" if none).
func (r *Registry) AppliedHash(ctx context.Context) (string, error) {
	q := r.Dialect.Quote
	var h string
	err := r.DB.QueryRowContext(ctx, "SELECT model_hash FROM "+q("_framework_schema_version")+" ORDER BY id DESC LIMIT 1").Scan(&h)
	if err != nil && strings.Contains(err.Error(), "no rows") {
		return "", nil
	}
	return h, err
}

// ApplySQL executes a migration or DDL script statement by statement in a
// transaction (MySQL DDL commits implicitly; the transaction still groups DML).
func (r *Registry) ApplySQL(ctx context.Context, script string) error {
	for _, stmt := range generator.SplitStatements(script) {
		if _, err := r.DB.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("%w\n  in: %s", err, firstLine(stmt))
		}
	}
	return nil
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		return s[:i] + " …"
	}
	return s
}

func (r *Registry) tables(ctx context.Context) (map[string]bool, error) {
	var query string
	if r.Dialect.Name() == "sqlite" {
		query = "SELECT name FROM sqlite_master WHERE type = 'table'"
	} else {
		query = "SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE()"
	}
	return r.names(ctx, query)
}

func (r *Registry) columns(ctx context.Context, table string) (map[string]bool, error) {
	if r.Dialect.Name() == "sqlite" {
		return r.names(ctx, "SELECT name FROM pragma_table_info(?)", table)
	}
	return r.names(ctx, "SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ?", table)
}

func (r *Registry) names(ctx context.Context, query string, args ...any) (map[string]bool, error) {
	rows, err := r.DB.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := map[string]bool{}
	for rows.Next() {
		var n string
		if err := rows.Scan(&n); err != nil {
			return nil, err
		}
		out[n] = true
	}
	return out, rows.Err()
}
