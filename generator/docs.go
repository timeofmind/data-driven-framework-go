package generator

import (
	"fmt"
	"sort"
	"strings"

	"github.com/timeofmind/data-driven-framework-go/model"
)

// Docs returns Markdown documentation for the whole model.
func Docs(m *model.Model) string {
	var b strings.Builder
	title := firstNonEmpty(m.Description, "Data Model")
	fmt.Fprintf(&b, "# %s\n\n", title)
	fmt.Fprintf(&b, "- Schema version: `%s`\n- Framework version: `%s`\n- Model hash: `%s`\n\n", m.SchemaVersion, m.FrameworkVersion, m.Hash())

	b.WriteString("## Contents\n\n")
	for _, c := range m.Classes() {
		fmt.Fprintf(&b, "- [%s](#%s)\n", c.EffectiveLabel(), anchor(c.Name))
	}
	if len(m.Enums()) > 0 {
		b.WriteString("- [Enumerations](#enumerations)\n")
	}
	b.WriteString("\n## Classes\n\n")

	for _, c := range m.Classes() {
		fmt.Fprintf(&b, "### %s\n\n", c.Name)
		if c.Label != "" && c.Label != c.Name {
			fmt.Fprintf(&b, "_%s_\n\n", c.Label)
		}
		if c.Description != "" {
			b.WriteString(c.Description + "\n\n")
		}
		if c.Abstract {
			b.WriteString("**Abstract** — no table; used as a parent class.\n\n")
		} else {
			fmt.Fprintf(&b, "Table: `%s`\n\n", c.EffectiveTable())
		}
		if c.HasParent() {
			fmt.Fprintf(&b, "Inherits from: [%s](#%s)\n\n", c.IsA, anchor(c.IsA))
		}
		if a := c.Access; a != nil {
			fmt.Fprintf(&b, "Access: read `%s`, write `%s`", firstNonEmpty(a.Read, "public"), firstNonEmpty(a.Write, "authenticated"))
			if a.Owner != "" {
				fmt.Fprintf(&b, ", owner slot `%s`", a.Owner)
			}
			if len(a.PublicWhen) > 0 {
				var conds []string
				for _, k := range sortedStringKeys(a.PublicWhen) {
					conds = append(conds, fmt.Sprintf("`%s = %s`", k, a.PublicWhen[k]))
				}
				fmt.Fprintf(&b, ", public when %s", strings.Join(conds, " and "))
			}
			b.WriteString("\n\n")
		}

		b.WriteString("| Field | Type | Required | Default | Description |\n|---|---|---|---|---|\n")
		for _, s := range c.AllSlots() {
			typ := s.Type
			if s.Type == "enum" {
				typ = fmt.Sprintf("enum([%s](#%s))", s.Enum, anchor(s.Enum))
			}
			var flags []string
			if s.Autogenerated {
				flags = append(flags, "auto")
			}
			if s.ReadOnly {
				flags = append(flags, "read-only")
			}
			if s.Hidden {
				flags = append(flags, "hidden")
			}
			if s.DefinedIn != "" && s.DefinedIn != c.Name {
				flags = append(flags, "from "+s.DefinedIn)
			}
			desc := s.Description
			if len(flags) > 0 {
				desc = strings.TrimSpace(desc + " _(" + strings.Join(flags, ", ") + ")_")
			}
			def := ""
			if s.Default != nil {
				def = "`" + *s.Default + "`"
			}
			req := ""
			if s.Required {
				req = "yes"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", s.Name, typ, req, def, mdCell(desc))
		}
		b.WriteString("\n")

		if len(c.Relationships) > 0 {
			b.WriteString("**Relationships**\n\n")
			for _, r := range c.Relationships {
				line := fmt.Sprintf("- `%s` — %s [%s](#%s)", r.Name, r.Kind, r.Target, anchor(r.Target))
				if r.Via != "" {
					line += fmt.Sprintf(" via `%s`", r.Via)
				}
				if r.Through != "" {
					line += fmt.Sprintf(" through `%s`", r.Through)
				}
				b.WriteString(line + "\n")
			}
			b.WriteString("\n")
		}
		if len(c.Constraints) > 0 {
			b.WriteString("**Constraints**\n\n")
			for _, k := range c.Constraints {
				fmt.Fprintf(&b, "- %s (`%s`)\n", k.Kind, strings.Join(k.Columns, "`, `"))
			}
			b.WriteString("\n")
		}
	}

	if len(m.Enums()) > 0 {
		b.WriteString("## Enumerations\n\n")
		for _, e := range m.Enums() {
			fmt.Fprintf(&b, "### %s\n\n", e.Name)
			if e.Description != "" {
				b.WriteString(e.Description + "\n\n")
			}
			for _, v := range e.Values {
				mark := ""
				if e.Default != nil && *e.Default == v {
					mark = " _(default)_"
				}
				fmt.Fprintf(&b, "- `%s`%s\n", v, mark)
			}
			b.WriteString("\n")
		}
	}
	return b.String()
}

func anchor(s string) string { return strings.ToLower(s) }

func mdCell(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ") }

func sortedStringKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
