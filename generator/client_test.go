package generator

import (
	"encoding/json"
	"strings"
	"testing"

	"github.com/timeofmind/data-driven-framework-go/schema"
)

func TestClientRules(t *testing.T) {
	m, err := schema.Load(schema.String(`
enums:
  Mode: {values: [walk, cycle]}
  Path: {values: [footpath, cycleway]}
classes:
  Kit:
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: mode, type: enum, enum: Mode}
  Trip:
    checks:
      - {check: "km > 0", message: "Give a distance", slot: km, client: true}
      - {check: "km < 1000", message: "Too far"}
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: kit_id, type: integer}
      - {name: km, type: float}
      - {name: mode, type: enum, enum: Mode}
      - {name: by_time, type: boolean}
      - {name: minutes, type: integer, when: "by_time", required_when: "by_time"}
    relationships:
      belongs_to: [{target: Kit, via: kit_id, match: {mode: mode}}]
  Stage:
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: trip_id, type: integer, hidden: true}
      - name: path
        type: enum
        enum: Path
        options: [{when: "trip.mode == 'walk'", values: [footpath]}]
    relationships:
      belongs_to: [{target: Trip, via: trip_id}]
`))
	if err != nil {
		t.Fatal(err)
	}
	rules := ClientRules(m)
	if rules["Kit"] != nil {
		t.Error("Kit has no rules")
	}
	trip, stage := rules["Trip"], rules["Stage"]
	if trip == nil || stage == nil {
		t.Fatalf("rules: %v", rules)
	}
	if trip.Types["by_time"] != "boolean" || trip.Types["mode"] != "enum" || trip.Types["km"] != "float" {
		t.Errorf("types: %v", trip.Types)
	}
	if len(trip.Checks) != 1 || trip.Checks[0].Message != "Give a distance" {
		t.Errorf("only client checks are shipped: %v", trip.Checks)
	}
	if len(trip.Match["kit_id"]) != 1 || trip.Match["kit_id"][0].Slot != "mode" || len(trip.Given) != 0 {
		t.Errorf("match / given: %+v %v", trip.Match, trip.Given)
	}
	if strings.Join(stage.Given, ",") != "trip.mode" {
		t.Errorf("stage given: %v", stage.Given)
	}
	b, _ := ClientRulesJSON(m)
	b2, _ := ClientRulesJSON(m)
	if string(b) != string(b2) || !strings.Contains(string(b), `"when":["id","by_time"]`) {
		t.Errorf("json: %s", b)
	}
	var back map[string]any
	if err := json.Unmarshal(b, &back); err != nil {
		t.Fatal(err)
	}
}
