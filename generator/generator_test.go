func TestMigration(t *testing.T) {
	from := load(t, `
schema_version: "1.0.0"
classes:
  A:
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: name, type: string}
      - {name: old, type: string}
      - {name: n, type: integer}
    constraints: {unique: [name]}
  Gone: {slots: [{name: id, type: integer, autogenerated: true}]}
`)
	to := load(t, `
schema_version: "1.1.0"
classes:
  A:
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: name, type: string, required: true}
      - {name: n, type: float}
      - {name: added, type: date}
  New: {slots: [{name: id, type: integer, autogenerated: true}]}
`)
	mig := NewMigration(from, to, dialect.MySQL{})
	mig.Now = func() time.Time { return time.Date(2026, 11, 4, 12, 0, 0, 0, time.UTC) }
	sql := mig.SQL()
	for _, want := range []string{
		"-- Migration: 1.0.0 -> 1.1.0 (mysql)",
		"DROP TABLE IF EXISTS `gones`;",
		"CREATE TABLE IF NOT EXISTS `news`",
		"ALTER TABLE `as` ADD COLUMN `added` DATE NULL;",
		"-- WARNING: DESTRUCTIVE: drops column and all its data\nALTER TABLE `as` DROP COLUMN `old`;",
		"-- WARNING: Type change may cause data loss\nALTER TABLE `as` MODIFY COLUMN `n` DOUBLE NULL;",
		"ALTER TABLE `as` MODIFY COLUMN `name` VARCHAR(255) NOT NULL;",
		"ALTER TABLE `as` DROP INDEX `uq_as_name`;",
		"INSERT INTO `_framework_schema_version`",
	} {
		if !strings.Contains(sql, want) {
			t.Errorf("migration missing %q\n%s", want, sql)
		}
	}
	sum := mig.Summary()
	if !strings.Contains(sum, "## ⚠ Dropped Tables (DESTRUCTIVE)") || !strings.Contains(sum, "`as`.`added`") {
		t.Errorf("summary:\n%s", sum)
	}
	if NewMigration(to, to, dialect.MySQL{}).SQL() != "" {
		t.Error("identical models should produce no migration")
	}
}
