func TestMySQLDDL(t *testing.T) {
	sql := SQL(device(t), dialect.MySQL{})
	for _, want := range []string{
		"CREATE TABLE IF NOT EXISTS `_framework_schema_version`",
		"CREATE TABLE IF NOT EXISTS `devices` (",
		"`id` INT NOT NULL AUTO_INCREMENT,\n  PRIMARY KEY (`id`)",
		"`status` ENUM('active', 'inactive', 'maintenance', 'retired') NULL DEFAULT 'active'",
		"`updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP",
		"CONSTRAINT `fk_devices_device_class_id_device_classes` FOREIGN KEY (`device_class_id`) REFERENCES `device_classes` (`id`)",
		"`id` INT NOT NULL COMMENT 'FK to parent devices'",
		"CONSTRAINT `fk_network_devices_devices` FOREIGN KEY (`id`) REFERENCES `devices` (`id`) ON DELETE CASCADE",
		"UNIQUE KEY `uq_interfaces_device_id_name` (`device_id`, `name`)",
		"`is_enabled` TINYINT(1) NULL DEFAULT 1",
	} {
		if !strings.Contains(sql, want) {
			t.Errorf("DDL missing %q", want)
		}
	}
	// Joined-table child stores only its own columns.
	nd := sql[strings.Index(sql, "CREATE TABLE IF NOT EXISTS `network_devices`"):]
	nd = nd[:strings.Index(nd, ";")]
	if strings.Contains(nd, "`hostname`") {
		t.Error("network_devices must not repeat inherited hostname")
	}
	// Parents come before children and FK targets.
	if strings.Index(sql, "`device_classes` (") > strings.Index(sql, "`devices` (") {
		t.Error("device_classes should be created before devices")
	}
}

func TestSQLiteDDLRunsAndSplits(t *testing.T) {
	stmts := SQLStatements(device(t), dialect.SQLite{})
	if len(stmts) < 8 {
		t.Fatalf("only %d statements", len(stmts))
	}
	for _, s := range stmts {
		if strings.HasPrefix(s, "--") {
			t.Errorf("comment leaked into statement: %q", s)
		}
	}
	got := SplitStatements("INSERT INTO t VALUES ('a;b'); -- c;\nSELECT 1;")
	if len(got) != 2 || got[0] != "INSERT INTO t VALUES ('a;b')" {
		t.Errorf("split: %q", got)
	}
}

func TestStringLengthAndOnDelete(t *testing.T) {
	m := load(t, `
classes:
  Owner: {slots: [{name: id, type: integer, autogenerated: true}]}
  Pet:
    slots:
      - {name: id, type: integer, autogenerated: true}
      - {name: owner_id, type: integer, required: true}
      - {name: nick, type: string, max: 40, description: "it's short"}
    relationships:
      belongs_to: [{target: Owner, via: owner_id, on_delete: cascade}]
`)
	sql := SQL(m, dialect.MySQL{})
	if !strings.Contains(sql, "`nick` VARCHAR(40) NULL COMMENT 'it''s short'") {
		t.Errorf("varchar/comment wrong:\n%s", sql)
	}
	if !strings.Contains(sql, "REFERENCES `owners` (`id`) ON DELETE CASCADE") {
		t.Error("on_delete cascade missing")
	}
}

func TestOpenAPI(t *testing.T) {
	spec := OpenAPI(device(t), OpenAPIOptions{Title: "Devices"})
	if spec["openapi"] != "3.0.3" {
		t.Fatal("version")
	}
	paths := spec["paths"].(map[string]any)
	for _, p := range []string{"/api/v1/devices", "/api/v1/devices/{id}", "/api/v1/device-classes", "/api/v1/network-devices/{id}"} {
		if _, ok := paths[p]; !ok {
			t.Errorf("missing path %s", p)
		}
	}
	schemas := spec["components"].(map[string]any)["schemas"].(map[string]any)
	in := schemas["DeviceInput"].(map[string]any)["properties"].(map[string]any)
	if _, ok := in["id"]; ok {
		t.Error("input schema must not include autogenerated id")
	}
	if _, ok := in["device_class_id"]; !ok {
		t.Error("input schema should include hidden FK device_class_id")
	}
	if _, err := OpenAPIYAML(device(t), OpenAPIOptions{}); err != nil {
		t.Error(err)
	}
}

func TestJSONSchema(t *testing.T) {
	b, err := JSONSchemaJSON(device(t))
	if err != nil {
		t.Fatal(err)
	}
	var doc map[string]any
	json.Unmarshal(b, &doc)
	defs := doc["definitions"].(map[string]any)
	dev := defs["Device"].(map[string]any)
	props := dev["properties"].(map[string]any)
	if _, hidden := props["device_class_id"]; hidden {
		t.Error("hidden slot leaked")
	}
	if props["id"].(map[string]any)["readOnly"] != true {
		t.Error("id should be readOnly")
	}
	vlan := defs["NetworkDevice"].(map[string]any)["properties"].(map[string]any)["vlan_id"].(map[string]any)
	if vlan["minimum"].(float64) != 1 || vlan["maximum"].(float64) != 4094 {
		t.Errorf("vlan bounds %v", vlan)
	}
	if defs["DeviceStatus"] == nil {
		t.Error("enum definition missing")
	}
}

func TestUI(t *testing.T) {
	cfg := ClassUI(device(t).Class("NetworkDevice"))
	var names []string
	for _, g := range cfg.Form.Groups {
		names = append(names, g.Name)
	}
	if strings.Join(names, ",") != "General,Hardware,Network" {
		t.Errorf("groups %v", names)
	}
	found := false
	for _, g := range cfg.Form.Groups {
		for _, f := range g.Fields {
			if f.Name == "device_class_id" && f.Type == "relation" && f.RelTarget == "DeviceClass" {
				found = true
			}
			if f.Name == "id" || f.Name == "created_at" {
				t.Errorf("read-only field %s in form", f.Name)
			}
		}
	}
	if !found {
		t.Error("FK selector for device_class_id missing")
	}

	dir := t.TempDir()
	files, err := WriteUI(device(t), dir)
	if err != nil || len(files) != 12 {
		t.Fatalf("WriteUI: %v (%d files)", err, len(files))
	}
	page := filepath.Join(dir, "device.html")
	b, _ := os.ReadFile(page)
	custom := strings.Replace(string(b), "</body>", "<p>custom</p>\n</body>", 1)
	os.WriteFile(page, []byte(custom), 0o644)
	WriteUI(device(t), dir)
	b, _ = os.ReadFile(page)
	if !strings.Contains(string(b), "<p>custom</p>") || strings.Count(string(b), uiBeginMarker) != 1 {
		t.Error("regeneration must keep content outside markers")
	}
}

