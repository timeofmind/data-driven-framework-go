// UIConfig is the per-class UI description (the Perl framework's <class>_ui.json).
// Front ends render lists and forms from it rather than from hand-written HTML.
type UIConfig struct {
	Class       string       `json:"class"`
	Label       string       `json:"label"`
	Table       string       `json:"table"`
	Description string       `json:"description"`
	List        UIList       `json:"list"`
	Form        UIForm       `json:"form"`
	Relations   []UIRelation `json:"relations"`
	Calendar    string       `json:"calendar,omitempty"`
	OrderBy     string       `json:"order_by,omitempty"`
}

type UIList struct {
	Columns []UIColumn `json:"columns"`
}

type UIColumn struct {
	Field    string `json:"field"`
	Label    string `json:"label"`
	Type     string `json:"type"`
	Sortable bool   `json:"sortable"`
}

type UIForm struct {
	Groups []UIGroup `json:"groups"`
}

type UIGroup struct {
	Name   string    `json:"name"`
	Fields []UIField `json:"fields"`
}

type UIField struct {
	Name        string     `json:"name"`
	Label       string     `json:"label"`
	Type        string     `json:"type"`
	Required    bool       `json:"required"`
	Group       string     `json:"group"`
	Order       int        `json:"order"`
	Placeholder string     `json:"placeholder"`
	Description string     `json:"description,omitempty"`
	APIReadOnly bool       `json:"api_read_only"`
	Default     *string    `json:"default,omitempty"`
	Options     []UIOption `json:"options,omitempty"`
	Min         *float64   `json:"min,omitempty"`
	Max         *float64   `json:"max,omitempty"`
	Step        string     `json:"step,omitempty"`
	Pattern     string     `json:"pattern,omitempty"`
	RelTarget   string     `json:"rel_target,omitempty"` // set when the field is a belongs_to FK
}

type UIOption struct {
	Value string `json:"value"`
	Label string `json:"label"`
}

type UIRelation struct {
	Field  string `json:"field"`
	Label  string `json:"label"`
	Target string `json:"target"`
}

// ClassUI builds the UI configuration for one class. FK slots that are hidden
// in the schema still appear in the form as relation selectors, unless the slot
// is the class's access owner (filled from the signed-in principal).
func ClassUI(c *model.Class) UIConfig {
	cfg := UIConfig{
		Class:       c.Name,
		Label:       c.EffectiveLabel(),
		Table:       c.EffectiveTable(),
		Description: c.Description,
		Calendar:    c.Calendar,
		OrderBy:     c.OrderBy,
	}
	for _, s := range c.VisibleSlots() {
		cfg.List.Columns = append(cfg.List.Columns, UIColumn{
			Field: s.Name, Label: s.EffectiveLabel(), Type: s.Type,
			Sortable: s.Type == "string" || s.Type == "integer" || s.Type == "float" || s.Type == "date" || s.Type == "datetime",
		})
	}
	owner := ""
	if c.Access != nil {
		owner = c.Access.Owner
	}
	var fields []UIField
	for _, s := range c.AllSlots() {
		if s.ReadOnly || s.Autogenerated || s.Name == owner {
			continue
		}
		rel := c.BelongsToVia(s.Name)
		if s.Hidden && rel == nil {
			continue
		}
		f := SlotUIField(s)
		if rel != nil {
			f.RelTarget = rel.Target
			f.Type = "relation"
			f.Label = firstNonEmpty(s.Label, rel.EffectiveLabel())
		}
		fields = append(fields, f)
	}
	sort.SliceStable(fields, func(i, j int) bool { return fields[i].Order < fields[j].Order })
	groups := map[string][]UIField{}
	var names []string
	for _, f := range fields {
		if _, seen := groups[f.Group]; !seen {
			names = append(names, f.Group)
		}
		groups[f.Group] = append(groups[f.Group], f)
	}
	// Ungrouped fields first, then groups in order of first appearance.
	sort.SliceStable(names, func(i, j int) bool { return names[i] == "" && names[j] != "" })
	for _, n := range names {
		cfg.Form.Groups = append(cfg.Form.Groups, UIGroup{Name: firstNonEmpty(n, "General"), Fields: groups[n]})
	}
	for _, r := range c.AllRelationships() {
		if r.IsBelongsTo() {
			cfg.Relations = append(cfg.Relations, UIRelation{Field: r.Via, Label: r.EffectiveLabel(), Target: r.Target})
		}
	}
	return cfg
}

func SlotUIField(s *model.Slot) UIField {
	f := UIField{
		Name:        s.Name,
		Label:       s.EffectiveLabel(),
		Type:        s.EffectiveControlType(),
		Required:    s.Required,
		Group:       s.UIGroup,
		Order:       s.UIOrder,
		Placeholder: s.Placeholder,
		Description: s.Description,
		APIReadOnly: s.APIReadOnly,
		Default:     s.Default,
		Min:         s.Min,
		Max:         s.Max,
		Pattern:     s.Pattern,
	}
	if s.Type == "float" {
		f.Step = "any"
	}
	if s.Type == "duration" && f.Placeholder == "" {
		f.Placeholder = "h:mm:ss"
	}
	if s.Type == "enum" && s.EnumObj != nil {
		for _, v := range s.EnumObj.Values {
			f.Options = append(f.Options, UIOption{Value: v, Label: s.EnumObj.Label(v)})
		}
	}
	return f
}

// EnumLabel turns an enum value into a display label: long_run -> Long run.
func EnumLabel(v string) string {
	v = strings.ReplaceAll(v, "_", " ")
	if v == "" {
		return v
	}
	return strings.ToUpper(v[:1]) + v[1:]
}

const (
	uiBeginMarker = "<!-- ### BEGIN GENERATED ### -->"
	uiEndMarker   = "<!-- ### END GENERATED ### -->"
)

var generatedBlock = regexp.MustCompile(`(?s)` + regexp.QuoteMeta(uiBeginMarker) + `.*?` + regexp.QuoteMeta(uiEndMarker))

// WriteUI writes <class>_ui.json and <class>.html for every concrete class into
// dir. Existing HTML keeps everything outside the generated markers.
func WriteUI(m *model.Model, dir string) ([]string, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	var files []string
	for _, c := range m.ConcreteClasses() {
		base := strings.ToLower(c.Name)
		cfgPath := filepath.Join(dir, base+"_ui.json")
		b, err := json.MarshalIndent(ClassUI(c), "", "  ")
		if err != nil {
			return nil, err
		}
		if err := os.WriteFile(cfgPath, append(b, '\n'), 0o644); err != nil {
			return nil, err
		}
		htmlPath := filepath.Join(dir, base+".html")
		if err := writeUIHTML(htmlPath, c); err != nil {
			return nil, err
		}
		files = append(files, cfgPath, htmlPath)
	}
	return files, nil
}

func writeUIHTML(path string, c *model.Class) error {
	block := uiBeginMarker + "\n" + UIHTMLBody(c) + "\n" + uiEndMarker
	var content string
	if existing, err := os.ReadFile(path); err == nil {
		if generatedBlock.Match(existing) {
			content = generatedBlock.ReplaceAllLiteralString(string(existing), block)
		} else {
			content = block + "\n\n" + string(existing)
		}
	} else {
		content = uiPage(c.EffectiveLabel(), block)
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

func uiPage(title, body string) string {
	return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>` + html.EscapeString(title) + `</title>
<style>
body { font-family: sans-serif; max-width: 900px; margin: 2em auto; padding: 0 1em; }
table { border-collapse: collapse; width: 100%; }
th, td { border: 1px solid #ccc; padding: 8px 12px; text-align: left; }
th { background: #f5f5f5; }
form { max-width: 600px; }
.field { margin-bottom: 1em; }
label { display: block; font-weight: bold; margin-bottom: 4px; }
input, select, textarea { width: 100%; padding: 6px; box-sizing: border-box; }
.required::after { content: ' *'; color: red; }
.btn { padding: 8px 16px; background: #0070f3; color: #fff; border: none; cursor: pointer; }
</style>
</head>
<body>
` + body + `
</body>
</html>
`
}

// UIHTMLBody renders the static list + form scaffold for a class.
func UIHTMLBody(c *model.Class) string {
	esc := html.EscapeString
	var heads, cells strings.Builder
	for _, s := range c.VisibleSlots() {
		heads.WriteString("<th>" + esc(s.EffectiveLabel()) + "</th>")
		cells.WriteString("<td><!-- " + esc(s.Name) + " --></td>")
	}
	var form strings.Builder
	for _, s := range c.FormSlots() {
		req := ""
		if s.Required {
			req = ` class="required"`
		}
		fmt.Fprintf(&form, "<div class=\"field\">\n  <label for=\"%s\"%s>%s</label>\n  %s\n</div>\n",
			esc(s.Name), req, esc(s.EffectiveLabel()), htmlInput(s))
	}
	return fmt.Sprintf(`<h1>%s</h1>
<h2>List</h2>
<table>
  <thead><tr>%s<th>Actions</th></tr></thead>
  <tbody>
    <tr>%s<td><a href="#">Edit</a> | <a href="#">Delete</a></td></tr>
  </tbody>
</table>
<h2>Create / Edit</h2>
<form method="post">
%s<button type="submit" class="btn">Save</button>
</form>`, esc(c.EffectiveLabel()), heads.String(), cells.String(), form.String())
}

func htmlInput(s *model.Slot) string {
	esc := html.EscapeString
	name := esc(s.Name)
	t := s.EffectiveControlType()
	switch {
	case t == "textarea":
		return fmt.Sprintf(`<textarea name="%s" id="%s"></textarea>`, name, name)
	case t == "select" && s.EnumObj != nil:
		var opts strings.Builder
		for _, v := range s.EnumObj.Values {
			fmt.Fprintf(&opts, `<option value="%s">%s</option>`, esc(v), esc(v))
		}
		return fmt.Sprintf(`<select name="%s" id="%s">%s</select>`, name, name, opts.String())
	case t == "checkbox":
		return fmt.Sprintf(`<input type="checkbox" name="%s" id="%s" value="1">`, name, name)
	}
	extra := ""
	if s.Placeholder != "" {
		extra += ` placeholder="` + esc(s.Placeholder) + `"`
	}
	if t == "number" {
		if s.Min != nil {
			extra += fmt.Sprintf(` min="%g"`, *s.Min)
		}
		if s.Max != nil {
			extra += fmt.Sprintf(` max="%g"`, *s.Max)
		}
	}
	if s.Pattern != "" {
		extra += ` pattern="` + esc(s.Pattern) + `"`
	}
	return fmt.Sprintf(`<input type="%s" name="%s" id="%s"%s>`, esc(t), name, name, extra)
}
