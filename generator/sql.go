// Package generator turns a resolved model.Model into artifacts: SQL DDL,
// migrations, OpenAPI, JSON Schema, UI scaffolding and Markdown docs.
// Generators are stateless and deterministic.
package generator

import (
	"fmt"
	"strings"

	"github.com/timeofmind/data-driven-framework-go/dialect"
	"github.com/timeofmind/data-driven-framework-go/model"
)

// SQL returns the complete DDL for the model in the given dialect.
func SQL(m *model.Model, d dialect.Dialect) string {
	parts := []string{
		sqlHeader(m, d) + d.Preamble(),
		d.MetadataTables(),
	}
	for _, c := range m.ConcreteClasses() {
		parts = append(parts, d.CreateTable(c, m))
	}
	parts = append(parts, d.Postamble())
	return strings.Join(parts, "\n")
}

// SQLStatements returns the DDL split into executable statements (for runtimes
// that apply a schema directly rather than via a .sql file).
func SQLStatements(m *model.Model, d dialect.Dialect) []string {
	return SplitStatements(SQL(m, d))
}

func sqlHeader(m *model.Model, d dialect.Dialect) string {
	return fmt.Sprintf(`-- ============================================================
-- Generated by data-driven-framework-go v%s (%s)
-- Schema version: %s
-- Model hash: %s
-- ============================================================
-- DO NOT EDIT THIS FILE MANUALLY.
-- Regenerate with: ddframework generate-sql --schema <schema.yaml>
-- ============================================================
`, Version, d.Name(), m.SchemaVersion, m.Hash())
}

// SplitStatements splits SQL text on top-level semicolons, ignoring "--"
// comments and semicolons inside quoted strings.
func SplitStatements(sqlText string) []string {
	var out []string
	var cur strings.Builder
	var quote rune
	lines := strings.Split(sqlText, "\n")
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if quote == 0 && strings.HasPrefix(trimmed, "--") {
			continue
		}
		runes := []rune(line)
		for i := 0; i < len(runes); i++ {
			r := runes[i]
			if quote == 0 && r == '-' && i+1 < len(runes) && runes[i+1] == '-' {
				break // trailing comment
			}
			if quote != 0 {
				cur.WriteRune(r)
				if r == quote {
					quote = 0
				}
				continue
			}
			switch r {
			case '\'', '"', '`':
				quote = r
				cur.WriteRune(r)
			case ';':
				if s := strings.TrimSpace(cur.String()); s != "" {
					out = append(out, s)
				}
				cur.Reset()
			default:
				cur.WriteRune(r)
			}
		}
		cur.WriteByte('\n')
	}
	if s := strings.TrimSpace(cur.String()); s != "" {
		out = append(out, s)
	}
	return out
}

// Version is the framework version reported in generated artifacts.
const Version = "0.2.0"
