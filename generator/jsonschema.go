package generator

import (
	"encoding/json"

	"github.com/timeofmind/data-driven-framework-go/model"
)

// JSONSchema returns a draft-07 document with one definition per enum and per
// concrete class.
func JSONSchema(m *model.Model) map[string]any {
	defs := map[string]any{}
	for _, e := range m.Enums() {
		defs[e.Name] = enumSchema(e)
	}
	for _, c := range m.ConcreteClasses() {
		defs[c.Name] = ClassJSONSchema(c)
	}
	title := m.Description
	if title == "" {
		title = "Generated Schema"
	}
	return map[string]any{
		"$schema":     "http://json-schema.org/draft-07/schema#",
		"$id":         "schema.json",
		"title":       title,
		"definitions": defs,
	}
}

// JSONSchemaJSON is JSONSchema encoded as indented JSON.
func JSONSchemaJSON(m *model.Model) ([]byte, error) {
	return json.MarshalIndent(JSONSchema(m), "", "  ")
}

func enumSchema(e *model.Enum) map[string]any {
	s := map[string]any{"type": "string", "enum": e.Values}
	if e.Description != "" {
		s["description"] = e.Description
	}
	return s
}

// ClassJSONSchema describes a record of the class as exchanged over the API.
// Password slots appear as writeOnly; hidden slots are omitted.
func ClassJSONSchema(c *model.Class) map[string]any {
	props := map[string]any{}
	var required []string
	for _, s := range c.AllSlots() {
		if s.Hidden {
			continue
		}
		props[s.Name] = SlotJSONSchema(s)
		if s.Required && !s.Autogenerated {
			required = append(required, s.Name)
		}
	}
	out := map[string]any{
		"type":                 "object",
		"properties":           props,
		"additionalProperties": false,
	}
	if len(required) > 0 {
		out["required"] = required
	}
	if c.Description != "" {
		out["description"] = c.Description
	}
	return out
}

func SlotJSONSchema(s *model.Slot) map[string]any {
	var out map[string]any
	if s.Type == "enum" && s.EnumObj != nil {
		out = map[string]any{"type": "string", "enum": s.EnumObj.Values}
	} else {
		out = model.JSONSchemaType(s.Type)
	}
	if s.Description != "" {
		out["description"] = s.Description
	}
	if s.ReadOnly || s.Autogenerated {
		out["readOnly"] = true
	}
	if s.Default != nil && !s.Autogenerated {
		out["default"] = typedDefault(s)
	}
	numeric := s.Type == "integer" || s.Type == "float"
	if s.Min != nil {
		if numeric {
			out["minimum"] = *s.Min
		} else {
			out["minLength"] = int(*s.Min)
		}
	}
	if s.Max != nil {
		if numeric {
			out["maximum"] = *s.Max
		} else {
			out["maxLength"] = int(*s.Max)
		}
	}
	if s.Pattern != "" {
		out["pattern"] = s.Pattern
	}
	return out
}

func typedDefault(s *model.Slot) any {
	d := *s.Default
	switch s.Type {
	case "integer", "float":
		var n json.Number = json.Number(d)
		if _, err := n.Float64(); err == nil {
			return n
		}
	case "boolean":
		return d == "1" || d == "true"
	}
	return d
}
