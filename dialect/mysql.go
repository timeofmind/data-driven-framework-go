package dialect

import (
	"fmt"
	"strings"

	"github.com/timeofmind/data-driven-framework-go/model"
)

// MySQL is the MySQL / MariaDB dialect, producing the same DDL as the Perl framework.
type MySQL struct{}

func (MySQL) Name() string       { return "mysql" }
func (MySQL) DriverName() string { return "mysql" }
func (MySQL) Quote(ident string) string {
	return "`" + strings.ReplaceAll(ident, "`", "``") + "`"
}
func (MySQL) Now() string { return "CURRENT_TIMESTAMP" }

func (MySQL) Preamble() string {
	return "SET FOREIGN_KEY_CHECKS = 0;\nSET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n"
}

func (MySQL) Postamble() string { return "SET FOREIGN_KEY_CHECKS = 1;\n" }

func (MySQL) MetadataTables() string {
	return "-- Framework metadata tables\n" +
		"CREATE TABLE IF NOT EXISTS `_framework_schema_version` (\n" +
		"  `id`                INT          NOT NULL AUTO_INCREMENT,\n" +
		"  `schema_version`    VARCHAR(50)  NOT NULL,\n" +
		"  `framework_version` VARCHAR(50)  NOT NULL,\n" +
		"  `applied_at`        DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,\n" +
		"  `model_hash`        VARCHAR(64)  NOT NULL,\n" +
		"  `notes`             TEXT,\n" +
		"  PRIMARY KEY (`id`)\n" +
		") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n\n" +
		"CREATE TABLE IF NOT EXISTS `_framework_migrations` (\n" +
		"  `id`            INT          NOT NULL AUTO_INCREMENT,\n" +
		"  `from_version`  VARCHAR(50),\n" +
		"  `to_version`    VARCHAR(50)  NOT NULL,\n" +
		"  `applied_at`    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,\n" +
		"  `migration_sql` TEXT         NOT NULL,\n" +
		"  `checksum`      VARCHAR(64),\n" +
		"  PRIMARY KEY (`id`)\n" +
		") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n"
}

func (d MySQL) columnType(s *model.Slot) string {
	switch s.Type {
	case "enum":
		if s.EnumObj != nil {
			return "ENUM(" + s.EnumObj.MySQLList() + ")"
		}
	case "string":
		if s.Max != nil && *s.Max <= 255 && *s.Max >= 1 {
			return fmt.Sprintf("VARCHAR(%d)", int(*s.Max))
		}
		return "VARCHAR(255)"
	}
	return model.MySQLType(s.Type)
}

func (d MySQL) ColumnDef(s *model.Slot, m *model.Model) string {
	parts := []string{d.Quote(s.Name), d.columnType(s)}
	switch {
	case s.Autogenerated && s.Type == "integer":
		parts = append(parts, "NOT NULL AUTO_INCREMENT")
		return strings.Join(parts, " ")
	case s.Autogenerated && s.Type == "datetime":
		if s.Name == "updated_at" {
			parts = append(parts, "NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP")
		} else {
			parts = append(parts, "NOT NULL DEFAULT CURRENT_TIMESTAMP")
		}
		return strings.Join(parts, " ")
	}
	if s.Required && !s.Autogenerated {
		parts = append(parts, "NOT NULL")
	} else {
		parts = append(parts, "NULL")
	}
	if s.Default != nil && !s.Autogenerated {
		parts = append(parts, "DEFAULT "+literalDefault(s))
	}
	if s.Description != "" {
		parts = append(parts, "COMMENT '"+escapeString(s.Description)+"'")
	}
	return strings.Join(parts, " ")
}

func (d MySQL) CreateTable(c *model.Class, m *model.Model) string {
	table := c.EffectiveTable()
	var cols, cons, fks []string

	if c.IsJoinedChild() {
		p := c.ParentClass
		pk := pkName(p)
		pt := p.EffectiveTable()
		cols = append(cols, fmt.Sprintf("  %s INT NOT NULL COMMENT 'FK to parent %s'", d.Quote(pk), pt))
		cons = append(cons, fmt.Sprintf("  PRIMARY KEY (%s)", d.Quote(pk)))
		fks = append(fks, fmt.Sprintf("  CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE CASCADE",
			d.Quote("fk_"+table+"_"+pt), d.Quote(pk), d.Quote(pt), d.Quote(pk)))
	}
	for _, s := range emittedSlots(c) {
		col := "  " + d.ColumnDef(s, m)
		if s.Autogenerated && s.Type == "integer" {
			col += ",\n  PRIMARY KEY (" + d.Quote(s.Name) + ")"
		}
		cols = append(cols, col)
	}
	seenFK := map[string]bool{}
	for _, r := range c.Relationships {
		if !r.IsBelongsTo() || seenFK[r.Via] {
			continue
		}
		seenFK[r.Via] = true
		t := m.Class(r.Target)
		if t == nil {
			continue
		}
		tt := t.EffectiveTable()
		fks = append(fks, fmt.Sprintf("  CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s)%s",
			d.Quote("fk_"+table+"_"+r.Via+"_"+tt), d.Quote(r.Via), d.Quote(tt), d.Quote(pkName(t)), onDeleteClause(r)))
	}
	for _, k := range c.UniqueConstraints() {
		cons = append(cons, fmt.Sprintf("  UNIQUE KEY %s (%s)", d.Quote(k.EffectiveName(table)), quoteList(d, k.Columns)))
	}
	for _, k := range c.IndexConstraints() {
		cons = append(cons, fmt.Sprintf("  INDEX %s (%s)", d.Quote(k.EffectiveName(table)), quoteList(d, k.Columns)))
	}

	defs := strings.Join(append(append(cols, cons...), fks...), ",\n")
	comment := ""
	if c.Description != "" {
		comment = " COMMENT='" + escapeString(c.Description) + "'"
	}
	return fmt.Sprintf("-- Class: %s (%s)\nCREATE TABLE IF NOT EXISTS %s (\n%s\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4%s;\n",
		c.EffectiveLabel(), c.Name, d.Quote(table), defs, comment)
}
