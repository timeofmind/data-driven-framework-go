package dialect

import (
	"fmt"
	"strings"

	"github.com/timeofmind/data-driven-framework-go/model"
)

// SQLite is the SQLite dialect. Enums become CHECK constraints, indexes become
// separate CREATE INDEX statements, and updated_at is maintained by the runtime
// (SQLite has no ON UPDATE CURRENT_TIMESTAMP).
type SQLite struct{}

func (SQLite) Name() string       { return "sqlite" }
func (SQLite) DriverName() string { return "sqlite" }
func (SQLite) Quote(ident string) string {
	return `"` + strings.ReplaceAll(ident, `"`, `""`) + `"`
}
func (SQLite) Now() string       { return "CURRENT_TIMESTAMP" }
func (SQLite) Preamble() string  { return "PRAGMA foreign_keys = OFF;\n" }
func (SQLite) Postamble() string { return "PRAGMA foreign_keys = ON;\n" }

func (SQLite) MetadataTables() string {
	return `-- Framework metadata tables
CREATE TABLE IF NOT EXISTS "_framework_schema_version" (
  "id"                INTEGER PRIMARY KEY AUTOINCREMENT,
  "schema_version"    TEXT NOT NULL,
  "framework_version" TEXT NOT NULL,
  "applied_at"        TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "model_hash"        TEXT NOT NULL,
  "notes"             TEXT
);

CREATE TABLE IF NOT EXISTS "_framework_migrations" (
  "id"            INTEGER PRIMARY KEY AUTOINCREMENT,
  "from_version"  TEXT,
  "to_version"    TEXT NOT NULL,
  "applied_at"    TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "migration_sql" TEXT NOT NULL,
  "checksum"      TEXT
);
`
}

func (d SQLite) ColumnDef(s *model.Slot, m *model.Model) string {
	parts := []string{d.Quote(s.Name), model.SQLiteType(s.Type)}
	switch {
	case s.Autogenerated && s.Type == "integer":
		return strings.Join(append(parts, "PRIMARY KEY AUTOINCREMENT"), " ")
	case s.Autogenerated && s.Type == "datetime":
		return strings.Join(append(parts, "NOT NULL DEFAULT CURRENT_TIMESTAMP"), " ")
	}
	if s.Required {
		parts = append(parts, "NOT NULL")
	}
	if s.Default != nil {
		parts = append(parts, "DEFAULT "+literalDefault(s))
	}
	if s.Type == "enum" && s.EnumObj != nil {
		parts = append(parts, fmt.Sprintf("CHECK (%s IN (%s))", d.Quote(s.Name), s.EnumObj.MySQLList()))
	}
	return strings.Join(parts, " ")
}

func (d SQLite) CreateTable(c *model.Class, m *model.Model) string {
	table := c.EffectiveTable()
	var cols, cons []string
	if c.IsJoinedChild() {
		p := c.ParentClass
		pk := pkName(p)
		cols = append(cols, fmt.Sprintf("  %s INTEGER NOT NULL PRIMARY KEY", d.Quote(pk)))
		cons = append(cons, fmt.Sprintf("  FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE CASCADE",
			d.Quote(pk), d.Quote(p.EffectiveTable()), d.Quote(pk)))
	}
	for _, s := range emittedSlots(c) {
		cols = append(cols, "  "+d.ColumnDef(s, m))
	}
	for _, k := range c.UniqueConstraints() {
		cons = append(cons, fmt.Sprintf("  CONSTRAINT %s UNIQUE (%s)", d.Quote(k.EffectiveName(table)), quoteList(d, k.Columns)))
	}
	seenFK := map[string]bool{}
	for _, r := range c.Relationships {
		if !r.IsBelongsTo() || seenFK[r.Via] {
			continue
		}
		seenFK[r.Via] = true
		t := m.Class(r.Target)
		if t == nil {
			continue
		}
		cons = append(cons, fmt.Sprintf("  FOREIGN KEY (%s) REFERENCES %s (%s)%s",
			d.Quote(r.Via), d.Quote(t.EffectiveTable()), d.Quote(pkName(t)), onDeleteClause(r)))
	}
	out := fmt.Sprintf("-- Class: %s (%s)\nCREATE TABLE IF NOT EXISTS %s (\n%s\n);\n",
		c.EffectiveLabel(), c.Name, d.Quote(table), strings.Join(append(cols, cons...), ",\n"))
	for _, k := range c.IndexConstraints() {
		out += fmt.Sprintf("CREATE INDEX IF NOT EXISTS %s ON %s (%s);\n",
			d.Quote(k.EffectiveName(table)), d.Quote(table), quoteList(d, k.Columns))
	}
	return out
}
